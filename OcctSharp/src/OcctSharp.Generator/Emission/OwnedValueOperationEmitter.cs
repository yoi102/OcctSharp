using System.Text;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
using OcctSharp.Generator.TypeMapping;
using static OcctSharp.Generator.Emission.GeometricOperationEmitter;

namespace OcctSharp.Generator.Emission;

/// <summary>Emits the exact audited catalogue of stable-address owning objects.</summary>
internal static class OwnedValueOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model,
        IReadOnlyList<SharedHandleScopeConfiguration> sharedScopes, IReadOnlySet<string> existing,
        IReadOnlyList<string> preambleHeaders)
    {
        var map = InitialTypeMap.FromModel(model);
        var shared = sharedScopes.ToDictionary(s => s.NativeType, StringComparer.Ordinal);
        BindingTypeProjection Map(BindingDeclaration d, BindingType t, BindingTypeUsage usage) =>
            OwnedValueOperationContract.TryMap(d, t, usage, map, out var p) && p is not null
                ? p : throw new InvalidDataException("Invalid audited owned signature: " + d.NativeSignature + " / " + t.CanonicalSpelling);
        var selected = model.Declarations.Where(d => !existing.Contains(d.StableId)
            && OwnedValueOperationContract.Contains(d)).OrderBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        if (selected.Length == 0) return new(version, [], []);
        var nativeOwners = selected.Select(Owner).Concat(selected.SelectMany(d => d.Parameters.Select(p => p.Type)
                .Concat(d.ReturnType is null ? [] : new[] { d.ReturnType }))
                .Where(t => OwnedValueOperationContract.Owners.Contains(Base(t))).Select(Base))
            .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        var records = model.Declarations.Where(d => d.Kind == BindingDeclarationKind.Record)
            .GroupBy(d => d.NativeName).ToDictionary(g => g.Key, g => g.First());
        List<GeneratedFile> files = [.. OwnedValueSupportEmitter.Emit()];
        foreach (var module in nativeOwners.GroupBy(o => records[o].ProductModule).OrderBy(g => g.Key))
        {
            var declarations = selected.Where(d => module.Contains(Owner(d))).ToArray();
            var allOperations = declarations.Concat(module.SelectMany(o => OwnedValueOperationContract.SupportingOperations(model, o))).ToArray();
            var usedShared = allOperations.SelectMany(d => d.Parameters.Select(p => p.Type.HandleTargetType)
                    .Append(d.ReturnType?.HandleTargetType)).Where(n => n is not null).Distinct()
                .Select(n => shared.TryGetValue(n!, out var s) ? s : throw new InvalidDataException("Owned operation needs unavailable shared scope " + n)).ToArray();
            string stem = "OcctSharp." + module.Key + ".OwnedValues.Generated";
            StringBuilder h = new("// <auto-generated />\n#pragma once\n#include \"../Geometry/OcctSharp.Geometry.Values.Generated.h\"\n");
            StringBuilder cpp = new("// <auto-generated />\n#include \"" + stem + ".h\"\n#include \"../Runtime/OcctSharp.Runtime.OwnedSupport.Generated.hxx\"\n#include <Standard_Failure.hxx>\nvoid OcctSharp_Internal_SetLastError(const char*);\n");
            cpp.Insert(0, string.Concat(preambleHeaders.Select(p => "#include <" + p + ">\n")));
            StringBuilder cs = new("// <auto-generated />\n#nullable enable\nusing System.Runtime.InteropServices;\nusing Microsoft.Win32.SafeHandles;\nusing OcctSharp.Generated;\nusing OcctSharp.Interop;\nusing OcctSharp.Values;\nnamespace OcctSharp.OwnedValues;\n");
            // All opaque names are declared without creating managed module dependencies.
            foreach (string owner in nativeOwners) h.AppendLine("typedef struct " + Handle(owner) + " " + Handle(owner) + ";");
            foreach (var sharedModule in usedShared.Select(s => records[s.NativeType].ProductModule).Distinct())
                h.AppendLine("#include \"../" + sharedModule + "/OcctSharp." + sharedModule + ".SharedHandles.Generated.h\"");
            foreach (string owner in module.Concat(allOperations.SelectMany(d => d.Parameters.Select(p => p.Type)
                    .Concat(d.ReturnType is null ? [] : new[] { d.ReturnType }))
                    .Where(t => nativeOwners.Contains(Base(t))).Select(Base)).Distinct())
                cpp.AppendLine("#include <" + owner + ".hxx>");
            foreach (var scope in usedShared)
            {
                cpp.AppendLine("namespace OcctSharpGenerated { const OcctSharp_" + scope.ManagedTypeName + "Handle* Validate" + scope.ManagedTypeName + "(const OcctSharp_" + scope.ManagedTypeName + "Handle*); }");
                cpp.AppendLine("namespace OcctSharpGenerated { OcctSharp_" + scope.ManagedTypeName + "Handle* Allocate" + scope.ManagedTypeName + "(opencascade::handle<" + scope.NativeType + ">); }");
            }
            h.AppendLine("#ifdef __cplusplus\nextern \"C\" {\n#endif");
            foreach (string owner in module)
            {
                string name = OwnedValueOperationContract.ManagedName(owner);
                string release = "occtsharp_owned_" + owner.ToLowerInvariant() + "_release";
                h.AppendLine("OCCTSHARP_API void OCCTSHARP_CALL " + release + "(" + Handle(owner) + "* handle);");
                cpp.AppendLine("void OCCTSHARP_CALL " + release + "(" + Handle(owner) + "* handle) { OcctSharpOwned::Release(handle, typeid(" + owner + ")); }");
                EmitClassStart(cs, owner, name, release);
                HashSet<string> signatures = [];
                int ordinal = 0;
                var supportingOperations = OwnedValueOperationContract.SupportingOperations(model, owner).ToArray();
                bool guardMakerResults = supportingOperations.Any(d => d.NativeName is "GC_Root::IsDone" or "gce_Root::IsDone");
                foreach (var d in declarations.Where(d => Owner(d) == owner))
                    EmitOperation(d, owner, name, ordinal++, Map, shared, h, cpp, cs, signatures, guardMakerResults);
                foreach (var d in supportingOperations)
                    EmitOperation(d, owner, name, ordinal++, Map, shared, h, cpp, cs, signatures, guardMakerResults);
                if (OwnedValueOperationContract.SupportingDefaultOwners.Contains(owner)
                    && !declarations.Any(d => Owner(d) == owner && d.Kind == BindingDeclarationKind.Constructor && d.Parameters.Count == 0))
                {
                    var supporting = new BindingDeclaration("support:owned-default:" + owner, owner + "::" + owner,
                        BindingDeclarationKind.Constructor, owner + ".hxx", 0, 0);
                    EmitOperation(supporting, owner, name, ordinal++, Map, shared, h, cpp, cs, signatures, guardMakerResults);
                }
                cs.AppendLine("}");
            }
            h.AppendLine("#ifdef __cplusplus\n}\n#endif");
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".h", h.ToString(), module.Key, GeneratedApiLayer.Raw, "OwnedValues"));
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".cpp", cpp.ToString(), module.Key, GeneratedApiLayer.Raw, "OwnedValues"));
            files.Add(new("src/OcctSharp/Generated/" + module.Key + "/" + module.Key + ".OwnedValues.Generated.cs", cs.ToString(), module.Key, GeneratedApiLayer.SafeManaged, "OwnedValues"));
        }
        return new(version, selected.Select(d => d.StableId).ToArray(), files);
    }

    private static void EmitClassStart(StringBuilder cs, string owner, string name, string release)
    {
        cs.AppendLine("/// <summary>Owns a stable-address " + owner + ". Synchronize mutation with other calls; dispose to release native storage.</summary>");
        cs.AppendLine("public sealed partial class " + name + " : IDisposable {");
        cs.AppendLine("  internal sealed class OwnedHandle : SafeHandleZeroOrMinusOneIsInvalid {\n    internal OwnedHandle(nint value) : base(true) => SetHandle(value);\n    protected override bool ReleaseHandle() { NativeRelease(handle); return true; }\n  }");
        cs.AppendLine("  private readonly OwnedHandle _handle;\n  private " + name + "(OwnedHandle handle) => _handle = handle;");
        cs.AppendLine("  static " + name + "() => NativeLibraryResolver.EnsureRegistered(typeof(" + name + ").Assembly);");
        cs.AppendLine("  internal OwnedHandle NativeHandle { get { ObjectDisposedException.ThrowIf(_handle.IsClosed, this); return _handle; } }");
        cs.AppendLine("  internal static " + name + " FromNative(nint value) {\n    try { return new " + name + "(new OwnedHandle(value)); }\n    catch { NativeRelease(value); throw; }\n  }");
        cs.AppendLine("  /// <summary>Releases native storage once active calls have finished.</summary>\n  public void Dispose() => _handle.Dispose();");
        cs.AppendLine("  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + release + "\")]\n  private static partial void NativeRelease(nint handle);");
    }

    private static void EmitOperation(BindingDeclaration d, string owner, string className, int ordinal,
        Func<BindingDeclaration, BindingType, BindingTypeUsage, BindingTypeProjection> map,
        Dictionary<string, SharedHandleScopeConfiguration> shared,
        StringBuilder h, StringBuilder cpp, StringBuilder cs, HashSet<string> signatures, bool guardMakerResults)
    {
        bool ctor = d.Kind == BindingDeclarationKind.Constructor;
        string member = d.NativeName[(d.NativeName.LastIndexOf("::", StringComparison.Ordinal) + 2)..];
        string method = ctor ? "Create" : member;
        string export = "occtsharp_owned_" + owner.ToLowerInvariant() + "_" + method.ToLowerInvariant() + "_" + ordinal;
        BindingTypeProjection? result = ctor ? null : map(d, d.ReturnType!, BindingTypeUsage.ReturnValue);
        bool returnsVoid = result?.RuleId == "TM000";
        List<string> abi = [], raw = [], friendly = [], args = [], locals = [], calls = [], copies = [], writes = [], assignments = [], outputs = [], guards = [];
        if (!ctor && !d.IsStatic)
        {
            abi.Add("const " + Handle(owner) + "* receiver"); raw.Add("OwnedHandle receiver"); args.Add("NativeHandle");
            locals.Add("auto self = OcctSharpOwned::Lease<" + owner + ">(receiver);");
        }
        for (int i = 0; i < d.Parameters.Count; i++)
        {
            var type = d.Parameters[i].Type;
            var p = map(d, type, BindingTypeUsage.Parameter);
            string name = "arg" + i, local = "local" + i;
            bool mutable = ReferenceOperationContract.IsMutableReference(type);
            if (p.RuleId == "TM010")
            {
                string target = Base(type), managed = OwnedValueOperationContract.ManagedName(target);
                abi.Add("const " + Handle(target) + "* " + name); raw.Add(managed + ".OwnedHandle " + name);
                friendly.Add(managed + " " + name); args.Add(name + ".NativeHandle"); guards.Add("ArgumentNullException.ThrowIfNull(" + name + ");");
                locals.Add("auto " + local + " = OcctSharpOwned::Lease<" + target + ">(" + name + ");"); calls.Add("*" + local);
            }
            else if (p.RuleId == "TM006")
            {
                var scope = shared[type.HandleTargetType!];
                abi.Add("const OcctSharp_" + scope.ManagedTypeName + "Handle* " + name);
                raw.Add(scope.ManagedTypeName + "Handle " + name); friendly.Add(scope.ManagedTypeName + " " + name);
                args.Add(name + ".NativeHandle"); guards.Add("ArgumentNullException.ThrowIfNull(" + name + ");");
                locals.Add("auto " + local + " = OcctSharpGenerated::Validate" + scope.ManagedTypeName + "(" + name + ")->Value;"); calls.Add(local);
            }
            else
            {
                abi.Add(p.AbiType + " " + name); raw.Add(RawType(p) + " " + name);
                friendly.Add((mutable ? "ref " : "") + p.ManagedFriendlyType + " " + name); args.Add(ToRaw(name, p));
                locals.Add("auto " + local + " = " + ToNative(name, p, Base(type)) + ";"); calls.Add(local);
            }
            if (mutable)
            {
                string output = "updatedArg" + i;
                abi.Add(p.AbiType + "* " + output); raw.Add("out " + RawType(p) + " " + output); args.Add("out " + RawType(p) + " " + output);
                outputs.Add(output); copies.Add("const auto copied" + i + " = " + FromNative(local, p) + ";");
                writes.Add("*" + output + " = copied" + i + ";"); assignments.Add(name + " = " + ToFriendly(output, p) + ";");
            }
        }
        string friendlyReturn = "void", returnExpression = "", publication = "";
        if (!returnsVoid)
        {
            string resultAbi, resultRaw;
            if (ctor || result!.RuleId == "TM010")
            {
                string target = ctor ? owner : Base(d.ReturnType!);
                friendlyReturn = OwnedValueOperationContract.ManagedName(target); resultAbi = Handle(target) + "*"; resultRaw = "nint";
                // Registration is the last potentially throwing action, after every copied output.
                publication = "auto* published = OcctSharpOwned::Publish<" + Handle(target) + ">(std::move(returned));";
                writes.Add("*result = published;"); returnExpression = friendlyReturn + ".FromNative(result)";
            }
            else if (result.RuleId == "TM006")
            {
                var scope = shared[d.ReturnType!.HandleTargetType!]; friendlyReturn = scope.ManagedTypeName + "?";
                resultAbi = "OcctSharp_" + scope.ManagedTypeName + "Handle*"; resultRaw = "nint";
                publication = "auto* published = returned.IsNull() ? nullptr : OcctSharpGenerated::Allocate" + scope.ManagedTypeName + "(std::move(returned));";
                writes.Add("*result = published;"); returnExpression = scope.ManagedTypeName + ".FromNative(result, \"" + export + "\")";
            }
            else
            {
                resultAbi = result.AbiType; resultRaw = RawType(result); friendlyReturn = result.ManagedFriendlyType;
                copies.Add("const auto copiedResult = " + FromNative("returned", result) + ";"); writes.Add("*result = copiedResult;"); returnExpression = ToFriendly("result", result);
            }
            abi.Add(resultAbi + "* result"); raw.Add("out " + resultRaw + " result"); args.Add("out " + resultRaw + " result"); outputs.Add("result");
        }
        string signature = "OcctSharp_Status OCCTSHARP_CALL " + export + "(" + string.Join(", ", abi) + ")";
        h.AppendLine("// Source: " + d.StableId + "\nOCCTSHARP_API " + signature + ";");
        cpp.AppendLine("// Source: " + d.StableId + "\n" + signature + " {");
        foreach (string output in outputs) cpp.AppendLine("  if (!" + output + ") { OcctSharp_Internal_SetLastError(\"Null owned operation output.\"); return OCCTSHARP_STATUS_INVALID_ARGUMENT; }");
        foreach (string output in outputs) cpp.AppendLine("  *" + output + " = {};");
        cpp.AppendLine("  OcctSharp_Internal_SetLastError(\"\");\n  try {");
        foreach (string local in locals) cpp.AppendLine("    " + local);
        if (guardMakerResults && !ctor && member is "Value" or "Operator")
            cpp.AppendLine("    if (!self->IsDone()) throw Standard_Failure(\"Owned maker has no result; check IsDone and Status.\");");
        string call = (d.IsStatic ? owner + "::" : "self->") + member + "(" + string.Join(", ", calls) + ")";
        if (ctor) cpp.AppendLine("    auto returned = std::make_shared<" + owner + ">(" + string.Join(", ", calls) + ");");
        else if (result!.RuleId == "TM010") cpp.AppendLine("    auto returned = std::make_shared<" + Base(d.ReturnType!) + ">(" + call + ");");
        else cpp.AppendLine("    " + (returnsVoid ? "" : "auto returned = ") + call + ";");
        foreach (string copy in copies) cpp.AppendLine("    " + copy);
        if (publication.Length != 0) cpp.AppendLine("    " + publication);
        foreach (string write in writes) cpp.AppendLine("    " + write);
        cpp.AppendLine("    return OCCTSHARP_STATUS_SUCCESS;\n  }\n  catch (const OcctSharpGenerated::GeneratedOperationFailure& error) { OcctSharp_Internal_SetLastError(error.what()); return error.Status; }\n  catch (const Standard_Failure& error) { OcctSharp_Internal_SetLastError(error.GetMessageString()); return OCCTSHARP_STATUS_OCCT_FAILURE; }\n  catch (const std::exception& error) { OcctSharp_Internal_SetLastError(error.what()); return OCCTSHARP_STATUS_STANDARD_EXCEPTION; }\n  catch (...) { OcctSharp_Internal_SetLastError(\"Unknown owned operation exception.\"); return OCCTSHARP_STATUS_UNKNOWN_EXCEPTION; }\n}");
        string baseMethod = method;
        int suffix = 2;
        while (!signatures.Add(method + "(" + string.Join(",", friendly) + ")")) method = baseMethod + suffix++;
        cs.AppendLine("  // Source: " + d.StableId + "\n  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + export + "\")]\n  private static partial NativeStatus Native_" + export + "(" + string.Join(", ", raw) + ");");
        cs.AppendLine("  /// <summary>Invokes " + d.NativeName + ". Native preconditions apply; ref outputs publish on success. Object mutations are not rolled back on failure.</summary>");
        cs.AppendLine("  public " + (ctor || d.IsStatic ? "static " : "") + friendlyReturn + " " + EnumBindingEmitter.ToIdentifier(method) + "(" + string.Join(", ", friendly) + ") {");
        foreach (string guard in guards) cs.AppendLine("    " + guard);
        cs.AppendLine("    NativeError.ThrowIfFailed(Native_" + export + "(" + string.Join(", ", args) + "), \"" + export + "\");");
        if (!returnsVoid) cs.AppendLine("    var managedResult = " + returnExpression + ";");
        foreach (string assignment in assignments) cs.AppendLine("    " + assignment);
        if (!returnsVoid) cs.AppendLine("    return managedResult;");
        cs.AppendLine("  }");
    }

    private static string Owner(BindingDeclaration d) => d.NativeName[..d.NativeName.IndexOf("::", StringComparison.Ordinal)];
    private static string Base(BindingType t) => t.BaseCanonicalSpelling.Replace("const ", "", StringComparison.Ordinal).Trim();
    private static string Handle(string owner) => "OcctSharp_Owned_" + owner + "Handle";
}
