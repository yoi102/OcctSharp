using System.Text.RegularExpressions;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;

namespace OcctSharp.Generator.Emission;

internal static class ClosedWorkflowOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model, ClosedWorkflowOperationContract contract)
    {
        var selected = model.Declarations.Where(contract.Contains).OrderBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        if (!selected.Any(d => !contract.Operations[d.StableId].Supporting)) return new(version, [], []);
        if (selected.Length != contract.Operations.Count)
            throw new InvalidDataException(contract.Name + " exact contract is incomplete or a pinned signature changed. Missing: "
                + string.Join(", ", contract.Operations.Keys.Except(selected.Select(d => d.StableId), StringComparer.Ordinal)));
        string stem = "OcctSharp." + contract.Module + "." + contract.Name + ".Generated";
        string sources = string.Concat(selected.Select(d => "// Source: " + d.StableId + "\n"));
        if (contract.Resource is "document-adapters" or "xde-adapters" or "step-adapters" or "mesh-exchange-adapters" or "mesh-resource-adapters" or "viewer-adapters" or "document-identity-adapters" or "render-resource-adapters")
            return PrivateDocumentOperationEmitter.Emit(version, selected, contract, sources);
        string native = CopiedCollectionSupportEmitter.Template(contract.Resource + "-native.txt");
        if (contract.Resource is "projection-adapters" or "fitting-adapters" or "topology-face-adapters" or "boolean-repair-adapters" or "local-feature-adapters" or "mesh-adapters")
            return new(version, selected.Where(d => d.SupportState != BindingSupportState.Manual).Select(d => d.StableId).ToArray(),
                [new("src/OcctSharp.Native/generated/" + contract.Module + "/OcctSharp." + contract.Module + "." + contract.Name + ".Generated.hxx",
                    "// <auto-generated />\n" + sources + native, contract.Module, GeneratedApiLayer.Raw, contract.Name)]);
        string declarations = string.Concat(Regex.Matches(native,
            @"^(?:OcctSharp_Status|void) OCCTSHARP_CALL [^\r\n{]+", RegexOptions.Multiline)
            .Select(m => "OCCTSHARP_API " + m.Value.Trim() + ";\n"));
        string header = "// <auto-generated />\n#pragma once\n#include \"../../include/OcctSharp.Native.h\"\n"
            + "#include \"../Geometry/OcctSharp.Geometry.SharedHandles.Generated.h\"\n"
            + "#ifdef __cplusplus\nextern \"C\" {\n#endif\n" + sources + declarations
            + "#ifdef __cplusplus\n}\n#endif\n";
        string managed = CopiedCollectionSupportEmitter.Template(contract.Resource + "-managed.txt");
        if (contract.Resource == "mesh-exchange-config")
        {
            int closing = managed.LastIndexOf('}');
            if (closing < 0) throw new InvalidDataException("Configured mesh managed class is missing.");
            managed = managed.Insert(closing, CopiedCollectionSupportEmitter.Template("mesh-exchange-resource-import-managed.txt"));
        }
        List<GeneratedFile> emitted =
        [
            new("src/OcctSharp.Native/generated/" + contract.Module + "/" + stem + ".h", header, contract.Module, GeneratedApiLayer.Raw, contract.Name),
            new("src/OcctSharp.Native/generated/" + contract.Module + "/" + stem + ".cpp", "// <auto-generated />\n#include \"" + stem + ".h\"\n" + sources + native, contract.Module, GeneratedApiLayer.Raw, contract.Name),
            new("src/OcctSharp/Generated/" + contract.Module + "/" + contract.Module + "." + contract.Name + ".Generated.cs", "// <auto-generated />\n" + sources + managed, contract.Module, GeneratedApiLayer.SafeManaged, contract.Name)
        ];
        if (contract.Resource == "document-projections")
            emitted.Add(new("src/OcctSharp.Native/generated/Documents/OcctSharp.Documents.ProjectionSupport.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("document-projections-support.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
        if (contract.Resource == "xde-metadata-workspaces")
        {
            emitted.Add(new("src/OcctSharp.Native/generated/Xde/OcctSharp.Xde.DocumentLifetimeSupport.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("xde-document-lifetime-support.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
            emitted.Add(new("src/OcctSharp.Native/generated/Xde/OcctSharp.Xde.ColorPersistenceSupport.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("xde-color-persistence-support.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
        }
        if (contract.Resource == "numeric-results")
        {
            emitted.Add(new("src/OcctSharp.Native/generated/Foundation/OcctSharp.Foundation.WorkflowResultSupport.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("workflow-result-support-native.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
            emitted.Add(new("src/OcctSharp/Generated/Foundation/Foundation.WorkflowResultSupport.Generated.cs",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("workflow-result-support-managed.txt"),
                contract.Module, GeneratedApiLayer.SafeManaged, contract.Name));
        }
        if (contract.Resource == "direct-collections")
            emitted.Add(new("src/OcctSharp.Native/generated/Documents/OcctSharp.Documents.DirectCollectionPersistence.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("direct-collections-persistence.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
        if (contract.Resource == "finite-extrema")
            emitted.Add(new("src/OcctSharp/Generated/Modeling/Modeling.FiniteExtremaGeometry.Generated.cs",
                "// <auto-generated />\n" + sources + CopiedCollectionSupportEmitter.Template("finite-extrema-geometry-managed.txt"),
                OcctProductModule.Modeling, GeneratedApiLayer.SafeManaged, contract.Name));
        if (contract.Resource == "local-step-export")
        {
            emitted.AddRange(PrivateStepExportWriterEmitter.Emit());
            emitted.Add(new("src/OcctSharp.Native/generated/Xde/OcctSharp.Xde.LocalStepExportNormalization.Generated.hxx",
                "// <auto-generated />\n" + CopiedCollectionSupportEmitter.Template("local-step-export-normalization-native.txt"),
                contract.Module, GeneratedApiLayer.Raw, contract.Name));
        }
        return new(version, selected.Where(d => d.SupportState != BindingSupportState.Manual).Select(d => d.StableId).ToArray(), emitted);
    }
}
