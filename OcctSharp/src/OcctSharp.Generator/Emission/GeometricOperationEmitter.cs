using System.Text;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
using OcctSharp.Generator.TypeMapping;

namespace OcctSharp.Generator.Emission;

internal static class GeometricOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model, IReadOnlySet<string> existing)
    {
        InitialTypeMap map = InitialTypeMap.FromModel(model);
        BindingDeclaration[] declarations = model.Declarations.Where(d => !existing.Contains(d.StableId)
            && GeometricOperationEligibility.IsEligible(d, map)).OrderBy(d => GeneratedBindingEpoch.Order(d))
            .ThenBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        if (declarations.Length == 0) return new(version, [], []);
        StringBuilder header = new("// <auto-generated />\n#pragma once\n#include \"OcctSharp.Geometry.Values.Generated.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
        StringBuilder native = new("// <auto-generated />\n#include \"OcctSharp.Geometry.ValueOperations.Generated.h\"\n#include <Standard_Failure.hxx>\n#include <stdexcept>\nvoid OcctSharp_Internal_SetLastError(const char*);\n");
        StringBuilder managed = new("// <auto-generated />\nusing System.Runtime.InteropServices;\nusing OcctSharp.Generated;\nusing OcctSharp.Interop;\nnamespace OcctSharp.ValueOperations;\n");
        foreach (string owner in declarations.Select(GeometricOperationEligibility.Owner).Distinct(StringComparer.Ordinal))
            native.AppendLine("#include <" + owner + ".hxx>");
        foreach (var group in declarations.GroupBy(GeometricOperationEligibility.Owner))
        {
            string owner = group.Key;
            BindingTypeProjection receiver = Projection(owner, map);
            string className = owner == "gp_Pnt" ? "Point3dOperations" : GeometryValueProjections.All.Single(v => v.NativeType == owner).Name + "Operations";
            managed.AppendLine("/// <summary>Copied OCCT " + owner + " operations; ref receivers change only after a successful call.</summary>");
            managed.AppendLine("public static partial class " + className + " {");
            managed.AppendLine("  static " + className + "() => NativeLibraryResolver.EnsureRegistered(typeof(" + className + ").Assembly);");
            Dictionary<string, int> exportOrdinals = new(StringComparer.Ordinal);
            HashSet<string> signatures = new(StringComparer.Ordinal);
            foreach (BindingDeclaration d in group)
            {
                bool ctor = d.Kind == BindingDeclarationKind.Constructor;
                bool mutate = !ctor && !d.IsConst;
                string member = d.NativeName[(owner.Length + 2)..];
                string baseName = ctor ? "Create" : member;
                string exportBase = "occtsharp_value_" + owner.ToLowerInvariant() + "_" + (ctor ? "create" : member.ToLowerInvariant());
                int ordinal = exportOrdinals.GetValueOrDefault(exportBase);
                exportOrdinals[exportBase] = ordinal + 1;
                string export = exportBase + "_" + ordinal.ToString(System.Globalization.CultureInfo.InvariantCulture);
                BindingTypeProjection result = ctor ? receiver : Map(d.ReturnType!, BindingTypeUsage.ReturnValue, map);
                var parameters = d.Parameters.Select((p, i) => (Type: p.Type, Name: "arg" + i.ToString(System.Globalization.CultureInfo.InvariantCulture), Projection: Map(p.Type, BindingTypeUsage.Parameter, map))).ToArray();
                List<string> abi = [], raw = [], friendly = [], args = [], invocationArgs = [];
                if (!ctor)
                {
                    abi.Add(receiver.AbiType + " receiver");
                    raw.Add(RawType(receiver) + " receiver");
                    friendly.Add((mutate ? "ref " : "") + receiver.ManagedFriendlyType + " receiver");
                    args.Add(ToRaw("receiver", receiver));
                }
                foreach (var p in parameters)
                {
                    abi.Add(p.Projection.AbiType + " " + p.Name);
                    raw.Add(RawType(p.Projection) + " " + p.Name);
                    friendly.Add(p.Projection.ManagedFriendlyType + " " + p.Name);
                    args.Add(ToRaw(p.Name, p.Projection));
                    invocationArgs.Add(ToNative(p.Name, p.Projection, p.Type.BaseCanonicalSpelling));
                }
                if (mutate)
                {
                    abi.Add(receiver.AbiType + "* updated");
                    raw.Add("out " + RawType(receiver) + " updated");
                    args.Add("out " + RawType(receiver) + " updated");
                }
                if (result.RuleId != "TM000")
                {
                    abi.Add(result.AbiType + "* result");
                    raw.Add("out " + RawType(result) + " result");
                    args.Add("out " + RawType(result) + " result");
                }
                string nativeSignature = "OcctSharp_Status OCCTSHARP_CALL " + export + "(" + (abi.Count == 0 ? "void" : string.Join(", ", abi)) + ")";
                header.AppendLine("// Source: " + d.StableId);
                header.AppendLine("OCCTSHARP_API " + nativeSignature + ";");
                native.AppendLine("// Source: " + d.StableId);
                native.AppendLine(nativeSignature + " {");
                List<string> outputs = [];
                if (mutate) outputs.Add("updated");
                if (result.RuleId != "TM000") outputs.Add("result");
                foreach (string output in outputs)
                    native.AppendLine("  if (" + output + " == nullptr) { OcctSharp_Internal_SetLastError(\"Null geometric operation output.\"); return OCCTSHARP_STATUS_INVALID_ARGUMENT; }");
                foreach (string output in outputs) native.AppendLine("  *" + output + " = {};");
                native.AppendLine("  OcctSharp_Internal_SetLastError(\"\");\n  try {");
                if (!ctor) native.AppendLine("    " + (d.IsConst ? "const " : "") + "auto value = " + ToNative("receiver", receiver, owner) + ";");
                if (owner is "gp_Mat" or "gp_Mat2d" or "gp_GTrsf" or "gp_GTrsf2d")
                {
                    if (member is "Invert" or "Inverted")
                        native.AppendLine("    if (value.IsSingular()) throw Standard_DomainError(\"Cannot invert a singular geometric value.\");");
                    else if (member is "Power" or "Powered")
                        native.AppendLine("    if (arg0 < 0 && value.IsSingular()) throw Standard_DomainError(\"Cannot apply a negative power to a singular geometric value.\");");
                }
                string invocation = (ctor ? owner : "value." + member) + "(" + string.Join(", ", invocationArgs) + ")";
                if (result.RuleId == "TM000") native.AppendLine("    " + invocation + ";");
                else native.AppendLine("    const auto returned = " + invocation + ";\n    const auto copiedResult = " + FromNative("returned", result) + ";");
                if (mutate) native.AppendLine("    const auto copiedReceiver = " + FromNative("value", receiver) + ";");
                if (result.RuleId != "TM000") native.AppendLine("    *result = copiedResult;");
                if (mutate) native.AppendLine("    *updated = copiedReceiver;");
                native.AppendLine("    return OCCTSHARP_STATUS_SUCCESS;\n  }\n  catch (const Standard_Failure& error) { OcctSharp_Internal_SetLastError(error.GetMessageString()); return OCCTSHARP_STATUS_OCCT_FAILURE; }\n  catch (const std::exception& error) { OcctSharp_Internal_SetLastError(error.what()); return OCCTSHARP_STATUS_STANDARD_EXCEPTION; }\n  catch (...) { OcctSharp_Internal_SetLastError(\"Unknown geometric operation exception.\"); return OCCTSHARP_STATUS_UNKNOWN_EXCEPTION; }\n}");
                string name = baseName;
                int suffix = 2;
                while (!signatures.Add(name + "(" + string.Join(",", friendly) + ")")) name = baseName + (suffix++).ToString(System.Globalization.CultureInfo.InvariantCulture);
                managed.AppendLine("  // Source: " + d.StableId);
                managed.AppendLine("  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + export + "\")]\n  private static partial NativeStatus Native_" + export + "(" + string.Join(", ", raw) + ");");
                managed.AppendLine("  /// <summary>Invokes " + d.NativeName + ". Native domain preconditions apply; no receiver change is published on failure.</summary>");
                managed.AppendLine("  public static " + result.ManagedFriendlyType + " " + EnumBindingEmitter.ToIdentifier(name) + "(" + string.Join(", ", friendly) + ") {");
                managed.AppendLine("    NativeError.ThrowIfFailed(Native_" + export + "(" + string.Join(", ", args) + "), \"" + export + "\");");
                if (mutate) managed.AppendLine("    receiver = " + ToFriendly("updated", receiver) + ";");
                if (result.RuleId != "TM000") managed.AppendLine("    return " + ToFriendly("result", result) + ";");
                managed.AppendLine("  }");
            }
            managed.AppendLine("}");
        }
        header.AppendLine("#ifdef __cplusplus\n}\n#endif");
        return new(version, declarations.Select(d => d.StableId).ToArray(),
        [
            File("src/OcctSharp.Native/generated/Geometry/OcctSharp.Geometry.ValueOperations.Generated.h", header, GeneratedApiLayer.Raw),
            File("src/OcctSharp.Native/generated/Geometry/OcctSharp.Geometry.ValueOperations.Generated.cpp", native, GeneratedApiLayer.Raw),
            File("src/OcctSharp/Generated/Geometry/Geometry.ValueOperations.Generated.cs", managed, GeneratedApiLayer.SafeManaged),
        ]);
    }

    private static GeneratedFile File(string path, StringBuilder text, GeneratedApiLayer layer) =>
        new(path, text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal), OcctProductModule.Geometry, layer, "ValueOperations");
    private static BindingTypeProjection Projection(string native, InitialTypeMap map) => Map(new(native, native, native, native,
        [new(BindingTypeLayerKind.Value, false)], null, [], false, null), BindingTypeUsage.ReturnValue, map);
    private static BindingTypeProjection Map(BindingType type, BindingTypeUsage usage, InitialTypeMap map) =>
        map.TryMap(type, usage, out BindingTypeProjection? result) ? result! : throw new InvalidDataException(type.CanonicalSpelling);
    internal static string RawType(BindingTypeProjection p) => p.RuleId == "TM005" ? "Point3dRaw" : p.ManagedRawType;
    internal static string ToRaw(string name, BindingTypeProjection p) => p.RuleId switch {
        "TM005" => "new Point3dRaw(" + name + ".X, " + name + ".Y, " + name + ".Z)",
        "TM004" => "(int)" + name, "TM003" => "(" + name + " ? 1 : 0)", _ => name };
    internal static string ToFriendly(string name, BindingTypeProjection p) => p.RuleId switch {
        "TM005" => "new Point3d(" + name + ".X, " + name + ".Y, " + name + ".Z)",
        "TM004" => "(" + p.ManagedFriendlyType + ")" + name, "TM003" => name + " != 0", _ => name };
    internal static string ToNative(string name, BindingTypeProjection p, string canonical) => p.RuleId switch {
        "TM009" => "OcctSharp_GeometryValues::ToNative(" + name + ")",
        "TM005" => "gp_Pnt(OcctSharp_GeometryValues::Check(" + name + ".x), OcctSharp_GeometryValues::Check(" + name + ".y), OcctSharp_GeometryValues::Check(" + name + ".z))",
        "TM004" => "static_cast<" + canonical + ">(" + name + ")",
        "TM008" => "static_cast<" + canonical + ">(" + name + ")",
        "TM003" => "(" + name + " != 0)",
        "TM002" => "OcctSharp_GeometryValues::Check(" + name + ")", _ => name };
    internal static string FromNative(string name, BindingTypeProjection p) => p.RuleId switch {
        "TM009" => "OcctSharp_GeometryValues::FromNative(" + name + ")",
        "TM005" => "OcctSharp_Point3d{" + name + ".X(), " + name + ".Y(), " + name + ".Z()}",
        "TM004" => "static_cast<int32_t>(" + name + ")", "TM003" => "(" + name + " ? 1 : 0)", _ => name };
}
