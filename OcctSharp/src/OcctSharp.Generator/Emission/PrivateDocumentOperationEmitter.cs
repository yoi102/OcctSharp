using System.Text;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;

namespace OcctSharp.Generator.Emission;

/// <summary>Semantic-model-driven native-only delegation; policy and copied ABI stay in the original caller.</summary>
internal static class PrivateDocumentOperationEmitter
{
    internal static string HelperName(string nativeName) => nativeName.Replace("::", "_", StringComparison.Ordinal);
    internal static string ConstructorName(string owner) => "Private" + owner.Replace("_", "", StringComparison.Ordinal);
    private static string NamespaceType(BindingType type, string owner) =>
        type.CanonicalSpelling.Contains(owner + "::", StringComparison.Ordinal)
            && !type.NativeSpelling.Contains(owner + "::", StringComparison.Ordinal)
        ? type.CanonicalSpelling : type.NativeSpelling;

    internal static GeneratedBindingSet Emit(string version, BindingDeclaration[] selected,
        ClosedWorkflowOperationContract contract, string sources)
    {
        StringBuilder code = new("// <auto-generated />\n" + sources + "#pragma once\n");
        // RTTI macro declarations retain the macro definition header in discovery.
        // Their actual SDK receiver must also be complete in a standalone adapter.
        var headers = selected.Select(d => d.Header).Concat(selected
            .Where(d => d.Header == "Standard_Type.hxx" && d.NativeName.EndsWith("::DynamicType", StringComparison.Ordinal))
            .Select(d => d.NativeName[..d.NativeName.LastIndexOf("::", StringComparison.Ordinal)] + ".hxx"));
        foreach (string header in headers.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
            code.Append("#include <").Append(header).Append(">\n");
        code.Append("#include <utility>\n#include <type_traits>\nnamespace OcctSharpGenerated::").Append(contract.Name).Append(" {\n");
        code.Append("// Borrowed SDK returns stay in the original call/parent scope. Existing callers own\n"
            + "// validation, command/epoch/thread guards, bounded copies and publication. No C ABI.\n");
        int index = 0;
        foreach (BindingDeclaration row in selected)
        {
            string owner = row.NativeName[..row.NativeName.LastIndexOf("::", StringComparison.Ordinal)];
            string member = row.NativeName[(row.NativeName.LastIndexOf("::", StringComparison.Ordinal) + 2)..];
            string parameters = string.Join(",", row.Parameters.Select(p => NamespaceType(p.Type, owner)));
            if (row.Kind == BindingDeclarationKind.Constructor)
            {
                code.Append("static_assert(std::is_constructible_v<").Append(owner);
                if (parameters.Length > 0) code.Append(',').Append(parameters);
                code.Append(">);\n");
                continue;
            }
            string signature = NamespaceType(row.ReturnType!, owner) + (row.IsStatic ? " (*)" : " (" + owner + "::*)")
                + "(" + parameters + ")" + (row.IsConst ? " const" : "")
                + (row.NativeSignature.EndsWith(" noexcept", StringComparison.Ordinal) ? " noexcept" : "");
            code.Append("using Signature").Append(index).Append('=').Append(signature).Append(";\n")
                .Append("inline constexpr Signature").Append(index).Append(" Exact").Append(index)
                .Append("=static_cast<Signature").Append(index).Append(">(&").Append(owner).Append("::").Append(member).Append(");\n");
            index++;
        }
        foreach (IGrouping<string, BindingDeclaration> group in selected.GroupBy(d => d.NativeName, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            BindingDeclaration row = group.First();
            string owner = row.NativeName[..row.NativeName.LastIndexOf("::", StringComparison.Ordinal)];
            string member = row.NativeName[(row.NativeName.LastIndexOf("::", StringComparison.Ordinal) + 2)..];
            if (row.Kind == BindingDeclarationKind.Constructor)
            {
                if (contract.Resource == "render-resource-adapters")
                {
                    // Typed overloads preserve the SDK's omitted trailing defaults.
                    // No default value is copied into the generator contract.
                    bool allocation = owner is "Graphic3d_CubeMapPacked" or "Graphic3d_CubeMapSeparate"
                        or "PrsDim_LengthDimension" or "PrsDim_RadiusDimension" or "PrsDim_DiameterDimension";
                    foreach (BindingDeclaration constructor in group)
                    {
                        int minimum = constructor.Parameters.Count;
                        while (minimum > 0 && constructor.Parameters[minimum - 1].HasDefaultArgument) minimum--;
                        for (int count = minimum; count <= constructor.Parameters.Count; count++)
                        {
                            code.Append("inline ").Append(owner).Append(allocation ? "*" : "")
                                .Append(" Construct").Append(owner.Replace("_", "", StringComparison.Ordinal)).Append('(')
                                .Append(string.Join(",", constructor.Parameters.Take(count).Select((p, i) => NamespaceType(p.Type, owner) + " arg" + i)))
                                .Append("){return ").Append(allocation ? "new " : "").Append(owner).Append('(')
                                .Append(string.Join(",", Enumerable.Range(0, count).Select(i => "arg" + i))).Append(");}\n");
                        }
                    }
                    continue;
                }
                // Value factories leave SDK return/parameter/copy types intact. Only the
                // semantically matched construction expression changes in the caller.
                if (contract.Resource == "viewer-adapters")
                {
                    // Preserve the SDK allocation expression and original registry
                    // transfer, without copying or deriving the transient receiver.
                    if (owner != "Graphic3d_ClipPlane") throw new InvalidDataException("Viewer allocation factory is not admitted: " + owner);
                    foreach (BindingDeclaration constructor in group)
                        code.Append("inline ").Append(owner).Append("* ConstructGraphic3dClipPlane(")
                            .Append(string.Join(",", constructor.Parameters.Select((p, i) => NamespaceType(p.Type, owner) + " arg" + i)))
                            .Append("){return new Graphic3d_ClipPlane(")
                            .Append(string.Join(",", constructor.Parameters.Select((_, i) => "arg" + i))).Append(");}\n");
                    continue;
                }
                if ((contract.Resource is "xde-adapters" or "mesh-exchange-adapters" or "mesh-resource-adapters" or "document-identity-adapters" or "render-resource-adapters") && owner != "XmlXCAFDrivers_DocumentStorageDriver")
                {
                    foreach (BindingDeclaration constructor in group)
                    {
                        code.Append("inline ").Append(owner).Append(" Construct").Append(owner.Replace("_", "", StringComparison.Ordinal)).Append('(')
                            .Append(string.Join(",", constructor.Parameters.Select((p, i) => NamespaceType(p.Type, owner) + " arg" + i)))
                            .Append("){return ").Append(owner).Append('(')
                            .Append(string.Join(",", constructor.Parameters.Select((_, i) => "arg" + i))).Append(");}\n");
                    }
                    continue;
                }
                string name = ConstructorName(owner);
                code.Append("class ").Append(name).Append(" : public ").Append(owner).Append(" {\npublic:\n")
                    .Append("template<class... Args> explicit ").Append(name).Append("(Args&&... args):")
                    .Append(owner).Append("(std::forward<Args>(args)...){ }\n};\n");
                continue;
            }
            if (row.NativeName == "TDF_Label::FindAttribute")
            {
                // Exact pinned TDF_Label.hxx short-circuit semantics: missing lookup
                // preserves the old typed handle, while a wrong-type found value clears it.
                code.Append("inline bool TDF_Label_FindAttribute(const TDF_Label& receiver,const Standard_GUID& id,occ::handle<TDF_Attribute>& result){return receiver.FindAttribute(id,result);}\n")
                    .Append("template<class T> inline bool TDF_Label_FindAttribute(const TDF_Label& receiver,const Standard_GUID& id,occ::handle<T>& result){occ::handle<TDF_Attribute> base;return TDF_Label_FindAttribute(receiver,id,base)&&!(result=occ::down_cast<T>(base)).IsNull();}\n");
                continue;
            }
            if (group.Any(d => d.IsStatic != row.IsStatic || d.IsConst != row.IsConst))
                throw new InvalidDataException("Private document overloads require one receiver profile: " + group.Key);
            code.Append("template<class... Args> inline decltype(auto) ").Append(HelperName(row.NativeName)).Append('(');
            if (!row.IsStatic) code.Append(row.IsConst ? "const " : "").Append(owner).Append("& receiver,");
            code.Append("Args&&... args){return ");
            if (row.IsStatic) code.Append(owner).Append("::").Append(member);
            else if (owner is "BinMDataStd_NamedDataDriver" or "XmlMDataStd_NamedDataDriver")
                code.Append("receiver.").Append(owner).Append("::").Append(member); // Preserve the original qualified base call.
            else code.Append("receiver.").Append(member);
            code.Append("(std::forward<Args>(args)...);}\n");
            if (!row.IsStatic && !row.IsConst)
                code.Append("template<class... Args> inline decltype(auto) ").Append(HelperName(row.NativeName))
                    .Append('(').Append(owner).Append("&& receiver,Args&&... args){return ")
                    .Append(HelperName(row.NativeName)).Append("(receiver,std::forward<Args>(args)...);}\n");
            if ((contract.Resource is "xde-adapters" or "step-adapters" or "mesh-exchange-adapters" or "mesh-resource-adapters" or "viewer-adapters" or "document-identity-adapters" or "render-resource-adapters") && !row.IsStatic)
            {
                // A bound call is the postfix expression of the invocation. C++17
                // therefore evaluates its receiver before its argument expressions,
                // exactly as for the original SDK member call. The pointer borrows
                // the SDK receiver without shortening a temporary's full-expression
                // lifetime; no SDK value or owning handle is copied into the closure.
                string helper = HelperName(row.NativeName);
                code.Append("inline auto ").Append(helper).Append("_Bind(")
                    .Append(row.IsConst ? "const " : "").Append(owner).Append("& receiver){return [address=&receiver](auto&&... args)->decltype(auto){return ")
                    .Append(helper).Append("(*address,std::forward<decltype(args)>(args)...);};}\n");
                if (!row.IsConst)
                    code.Append("inline auto ").Append(helper).Append("_Bind(").Append(owner)
                        .Append("&& receiver){return ").Append(helper).Append("_Bind(receiver);}\n");
            }
        }
        code.Append("}\n");
        return new(version, selected.Where(d => d.SupportState != BindingSupportState.Manual).Select(d => d.StableId).ToArray(),
            [new("src/OcctSharp.Native/generated/" + contract.Module + "/OcctSharp." + contract.Module + "." + contract.Name + ".Generated.hxx",
                code.ToString(), contract.Module, GeneratedApiLayer.Raw, contract.Name)]);
    }
}
