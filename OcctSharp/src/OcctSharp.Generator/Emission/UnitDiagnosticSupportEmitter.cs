using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;

namespace OcctSharp.Generator.Emission;

/// <summary>Composes existing exact unit and diagnostic contracts without claiming new SDK coverage.</summary>
internal static class UnitDiagnosticSupportEmitter
{
    internal static readonly IReadOnlyDictionary<string, CopiedCollectionOperationContract.Operation> Dependencies =
        CopiedCollectionOperationContract.Load("unit-diagnostic-support-contracts.json").Operations;

    internal static IReadOnlyList<GeneratedFile> Emit(BindingModel model)
    {
        var present = model.Declarations.Where(d => Dependencies.ContainsKey(d.StableId)).ToArray();
        if (present.Length == 0) return [];
        if (present.Length != Dependencies.Count || present.Select(d => d.StableId).Distinct(StringComparer.Ordinal).Count() != Dependencies.Count
            || present.Any(d => Dependencies[d.StableId].NativeName != d.NativeName || Dependencies[d.StableId].Signature != d.NativeSignature
                || !(ClosedWorkflowOperationContract.FoundationValues.Contains(d) || ClosedWorkflowOperationContract.FoundationDiagnostics.Contains(d))))
            throw new InvalidDataException("UnitDiagnosticWorkflow requires the complete unchanged unit/message dependency contracts.");
        string sources = string.Concat(present.OrderBy(d => d.StableId, StringComparer.Ordinal).Select(d => "// Reused dependency: " + d.StableId + "\n"));
        return [new("src/OcctSharp/Generated/Foundation/Foundation.UnitDiagnosticWorkflow.Generated.cs",
            "// <auto-generated />\n// Generated composition; no additional SDK declaration coverage.\n" + sources
                + CopiedCollectionSupportEmitter.Template("unit-diagnostic-workflow-managed.txt"),
            OcctProductModule.Foundation, GeneratedApiLayer.SafeManaged, "UnitDiagnosticWorkflow")];
    }
}
