using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;

namespace OcctSharp.Generator.Emission;

/// <summary>Bounded, hash-pinned application prerequisites; no raw declaration credit.</summary>
public static class ConsumerSupportWorkflowEmitter
{
    public const string Workflow = "exact-consumer-v1";
    public static IReadOnlyList<GeneratedFile> Emit(DiscoveryConfiguration configuration, string occtRoot)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        if (configuration.ConsumerSupportWorkflows.Count == 0) return [];
        if (configuration.OcctVersion != "8.0.1" || configuration.ConsumerSupportWorkflows.Count != 1
            || configuration.ConsumerSupportWorkflows[0] != Workflow)
            throw new InvalidDataException("Unknown, duplicate or unaudited consumer workflow.");
        using JsonDocument contract = ReadContract();
        var fingerprints = contract.RootElement.GetProperty("headers").EnumerateObject()
            .ToDictionary(x => x.Name, x => x.Value.GetString()!, StringComparer.Ordinal);
        ViewerSupportWorkflowEmitter.ValidateHeaderFingerprints(fingerprints,
            name => File.ReadAllBytes(Path.Combine(Path.GetFullPath(occtRoot), "inc", name)));
        return CreateFiles(contract.RootElement);
    }
    internal static IReadOnlyList<GeneratedFile> CreateFiles(JsonElement contract)
    {
        List<GeneratedFile> files = [];
        foreach (var row in contract.GetProperty("files").EnumerateArray())
        {
            string path = row.GetProperty("output").GetString()!;
            string resource = row.GetProperty("template").GetString()!;
            if (!(path.StartsWith("src/OcctSharp.Native/generated/Modeling/", StringComparison.Ordinal)
                || path.StartsWith("src/OcctSharp.Native/generated/Visualization/", StringComparison.Ordinal)
                || path.StartsWith("src/OcctSharp/Generated/Consumers/", StringComparison.Ordinal)
                || path.StartsWith("src/OcctSharp/Generated/Modeling/", StringComparison.Ordinal)) || path.Contains("..", StringComparison.Ordinal)
                || path.Contains('\\') || Path.GetFileName(resource) != resource)
                throw new InvalidDataException("Consumer generation contract escaped its allowed source roots.");
            string source = Template(resource).Replace("\r\n", "\n", StringComparison.Ordinal);
            if (!source.EndsWith('\n')) source += "\n";
            string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)));
            if (fingerprint != row.GetProperty("templateSha256").GetString())
                throw new InvalidDataException("Consumer support template changed without exact admission: " + resource);
            string moduleName = row.GetProperty("module").GetString()!;
            if (moduleName is not ("Modeling" or "Visualization"))
                throw new InvalidDataException("Consumer support module was not admitted.");
            files.Add(new(path, "// <auto-generated />\n// Consumer support: " + Workflow
                + "; template SHA256: " + fingerprint + "\n"
                + (path.EndsWith(".cs", StringComparison.Ordinal) ? "#nullable enable\n" : "")
                + source, Enum.Parse<OcctProductModule>(moduleName),
                path.EndsWith(".cs", StringComparison.Ordinal) ? GeneratedApiLayer.SafeManaged : GeneratedApiLayer.Runtime, "ExactConsumerSupport"));
        }
        if (files.Select(f => f.RelativePath).Distinct(StringComparer.Ordinal).Count() != files.Count)
            throw new InvalidDataException("Duplicate consumer support output.");
        return files;
    }
    internal static JsonDocument ReadContract() => JsonDocument.Parse(Template("consumer-support-contract.json"));
    private static string Template(string name)
    {
        using Stream stream = typeof(ConsumerSupportWorkflowEmitter).Assembly.GetManifestResourceStream("OcctSharp.Generator.Emission." + name)
            ?? throw new InvalidDataException("Consumer support resource is missing: " + name);
        using StreamReader reader = new(stream, Encoding.UTF8); return reader.ReadToEnd();
    }
}
