using System.Text.RegularExpressions;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
namespace OcctSharp.Generator.Emission;
internal static class SplineWorkspacesOperationEmitter {
 internal static GeneratedBindingSet Emit(string version,BindingModel model) {
  var selected=model.Declarations.Where(SplineWorkspacesOperationContract.Contains).OrderBy(d=>d.StableId,StringComparer.Ordinal).ToArray();
  if(selected.Length==0)return new(version,[],[]);
  if(selected.Length!=SplineWorkspacesOperationContract.Operations.Count)throw new InvalidDataException("AM exact contract is incomplete or a pinned signature changed.");
  const string stem="OcctSharp.Geometry.SplineWorkspaces.Generated";
  string sources=string.Concat(selected.Select(d=>"// Source: "+d.StableId+"\n"));
  string native=CopiedCollectionSupportEmitter.Template("spline-workspaces-native.txt");
  string declarations=string.Concat(Regex.Matches(native,@"^(?:OcctSharp_Status|void) OCCTSHARP_CALL [^\r\n{]+",RegexOptions.Multiline).Select(m=>"OCCTSHARP_API "+m.Value.Trim()+";\n"));
  string header="// <auto-generated />\n#pragma once\n#include \"../../include/OcctSharp.Native.h\"\n#include \"OcctSharp.Geometry.SharedHandles.Generated.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"+sources+declarations+"#ifdef __cplusplus\n}\n#endif\n";
  return new(version,selected.Where(d=>d.SupportState!=BindingSupportState.Manual).Select(d=>d.StableId).ToArray(),[
   new("src/OcctSharp.Native/generated/Geometry/"+stem+".h",header,OcctProductModule.Geometry,GeneratedApiLayer.Raw,"SplineWorkspaces"),
   new("src/OcctSharp.Native/generated/Geometry/"+stem+".cpp","// <auto-generated />\n#include \""+stem+".h\"\n"+sources+native,OcctProductModule.Geometry,GeneratedApiLayer.Raw,"SplineWorkspaces"),
   new("src/OcctSharp/Generated/Geometry/Geometry.SplineWorkspaces.Generated.cs","// <auto-generated />\n"+sources+CopiedCollectionSupportEmitter.Template("spline-workspaces-managed.txt"),OcctProductModule.Geometry,GeneratedApiLayer.SafeManaged,"SplineWorkspaces")]);
 }
}
