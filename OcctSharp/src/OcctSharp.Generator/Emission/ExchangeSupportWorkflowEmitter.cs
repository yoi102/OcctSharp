using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;

namespace OcctSharp.Generator.Emission;

/// <summary>Internal exact STEP graph completion; no new native address or public lifetime category.</summary>
public static class ExchangeSupportWorkflowEmitter
{
    public const string ExactOffsetWorkflow="step-exact-offset-v1";
    private const string ResourcePrefix="OcctSharp.Generator.Emission.";
    public static IReadOnlyList<GeneratedFile> Emit(DiscoveryConfiguration configuration,string occtRoot)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        if(configuration.ExchangeSupportWorkflows.Count==0)return [];
        ValidateWorkflowSelection(configuration);
        ArgumentException.ThrowIfNullOrWhiteSpace(occtRoot);
        string includeRoot=Path.Combine(Path.GetFullPath(occtRoot),"inc");
        ValidateHeaderFingerprints(HeaderFingerprints(),header=>File.ReadAllBytes(Path.Combine(includeRoot,header)));
        return CreateExactOffsetFiles();
    }
    internal static void ValidateWorkflowSelection(DiscoveryConfiguration configuration)
    {
        if(configuration.OcctVersion!="8.0.1"||configuration.ExchangeSupportWorkflows.Count!=1
            ||configuration.ExchangeSupportWorkflows[0]!=ExactOffsetWorkflow)
            throw new InvalidDataException("Exact offset STEP support requires one audited OCCT 8.0.1 workflow.");
    }
    internal static IReadOnlyDictionary<string,string> HeaderFingerprints()
    {
        using JsonDocument contract=JsonDocument.Parse(Template("step-exact-offset-contract.json"));
        return contract.RootElement.GetProperty("headers").EnumerateObject()
            .ToDictionary(row=>row.Name,row=>row.Value.GetString()!,StringComparer.Ordinal);
    }
    internal static void ValidateHeaderFingerprints(IReadOnlyDictionary<string,string> expected,Func<string,byte[]> readHeader)
    {
        foreach(var row in expected.OrderBy(row=>row.Key,StringComparer.Ordinal))
        {
            if(Path.GetFileName(row.Key)!=row.Key||row.Key.Contains("..",StringComparison.Ordinal))
                throw new InvalidDataException("Exact STEP header escaped the audited SDK include directory.");
            if(!string.Equals(Convert.ToHexString(SHA256.HashData(readHeader(row.Key))),row.Value,StringComparison.Ordinal))
                throw new InvalidDataException("Audited exact STEP header changed: "+row.Key);
        }
    }
    internal static IReadOnlyList<GeneratedFile> CreateExactOffsetFiles()=>
    [
        Generated("src/OcctSharp.Native/generated/DataExchange/OcctSharp.ExactStepOffsets.Generated.hxx","step-exact-offset-header.txt"),
        Generated("src/OcctSharp.Native/generated/DataExchange/OcctSharp.ExactStepOffsets.Generated.cpp","step-exact-offset-native.txt")
    ];
    private static GeneratedFile Generated(string path,string resource)
    {
        string source=Template(resource).Replace("\r\n","\n",StringComparison.Ordinal);
        if(!source.EndsWith('\n'))source+="\n";
        string fingerprint=Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)));
        SupportWorkflowTemplateGuard.Require(typeof(ExchangeSupportWorkflowEmitter), "step-exact-offset-contract.json", resource, fingerprint);
        return new(path,"// <auto-generated />\n// Exchange support workflow: "+ExactOffsetWorkflow+
            "; template SHA256: "+fingerprint+"\n"+source,OcctProductModule.DataExchange,GeneratedApiLayer.Runtime,"ExactStepOffsetSupport");
    }
    private static string Template(string name)
    {
        using Stream stream=typeof(ExchangeSupportWorkflowEmitter).Assembly.GetManifestResourceStream(ResourcePrefix+name)
            ??throw new InvalidDataException("Exact STEP generation input is missing: "+name);
        using StreamReader reader=new(stream,Encoding.UTF8);return reader.ReadToEnd();
    }
}
