using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;

namespace OcctSharp.Generator.Emission;

/// <summary>Generates bounded viewer support glue; it does not admit raw graphics handles or new declaration IDs.</summary>
public static class ViewerSupportWorkflowEmitter
{
    public const string RenderingHealthWorkflow = "render-health-v1";
    private const string ResourcePrefix = "OcctSharp.Generator.Emission.";

    public static IReadOnlyList<GeneratedFile> Emit(DiscoveryConfiguration configuration, string occtRoot)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        if (configuration.ViewerSupportWorkflows.Count == 0) return [];
        ValidateWorkflowSelection(configuration);
        ArgumentException.ThrowIfNullOrWhiteSpace(occtRoot);
        string includeRoot = Path.Combine(Path.GetFullPath(occtRoot), "inc");
        ValidateHeaderFingerprints(HeaderFingerprints(), header => File.ReadAllBytes(Path.Combine(includeRoot, header)));
        return CreateRenderingHealthFiles();
    }

    internal static void ValidateWorkflowSelection(DiscoveryConfiguration configuration)
    {
        if (configuration.OcctVersion != "8.0.1")
            throw new InvalidDataException("Viewer rendering health support targets audited OCCT 8.0.1 headers only.");
        if (configuration.ViewerSupportWorkflows.Count != 1
            || configuration.ViewerSupportWorkflows[0] != RenderingHealthWorkflow)
            throw new InvalidDataException("Unknown or duplicate viewer support workflow; no output was emitted.");
    }

    internal static IReadOnlyDictionary<string, string> HeaderFingerprints()
    {
        using JsonDocument contract = JsonDocument.Parse(Template("viewer-render-health-contract.json"));
        return contract.RootElement.GetProperty("headers").EnumerateObject()
            .ToDictionary(row => row.Name, row => row.Value.GetString()!, StringComparer.Ordinal);
    }

    internal static void ValidateHeaderFingerprints(IReadOnlyDictionary<string, string> expected,
        Func<string, byte[]> readHeader)
    {
        foreach (var row in expected.OrderBy(row => row.Key, StringComparer.Ordinal))
        {
            if (Path.GetFileName(row.Key) != row.Key || row.Key.Contains("..", StringComparison.Ordinal))
                throw new InvalidDataException("Viewer support header contract escaped the SDK include directory.");
            if (!string.Equals(Convert.ToHexString(SHA256.HashData(readHeader(row.Key))), row.Value,
                StringComparison.Ordinal))
                throw new InvalidDataException("Audited viewer support SDK header changed: " + row.Key);
        }
    }

    internal static IReadOnlyList<GeneratedFile> CreateRenderingHealthFiles() =>
    [
        Generated("src/OcctSharp.Native/generated/Visualization/OcctSharp.ViewerRenderingHealth.Generated.h",
            "viewer-render-health-header.txt", OcctProductModule.Visualization),
        Generated("src/OcctSharp.Native/generated/Visualization/OcctSharp.ViewerRenderingHealth.Generated.cpp",
            "viewer-render-health-native.txt", OcctProductModule.Visualization),
        Generated("src/OcctSharp/Generated/ViewerRenderingHealth.Generated.cs",
            "viewer-render-health-facade.txt", OcctProductModule.Visualization),
        // Retain the existing legacy interop assembly/NativeMethods partial owner.
        Generated("src/OcctSharp/Generated/Modeling/ViewerRenderingHealth.NativeMethods.Generated.cs",
            "viewer-render-health-interop.txt", OcctProductModule.Modeling),
    ];

    private static GeneratedFile Generated(string path, string resource, OcctProductModule module)
    {
        string source = Template(resource).Replace("\r\n", "\n", StringComparison.Ordinal);
        if (!source.EndsWith('\n')) source += "\n";
        string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)));
        return new(path, "// <auto-generated />\n// Viewer support workflow: " + RenderingHealthWorkflow
            + "; template SHA256: " + fingerprint + "\n" + source, module,
            GeneratedApiLayer.Runtime, "ViewerRenderingHealthSupport");
    }

    private static string Template(string name)
    {
        using Stream stream = typeof(ViewerSupportWorkflowEmitter).Assembly.GetManifestResourceStream(ResourcePrefix + name)
            ?? throw new InvalidDataException("Viewer support generation input is missing: " + name);
        using StreamReader reader = new(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }
}
