using System.Text.RegularExpressions;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
namespace OcctSharp.Generator.Emission;
internal static class NumericMatricesOperationEmitter {
 internal static GeneratedBindingSet Emit(string version,BindingModel model) {
  var selected=model.Declarations.Where(NumericMatricesOperationContract.Contains).OrderBy(d=>d.StableId,StringComparer.Ordinal).ToArray();
  if(selected.Length==0)return new(version,[],[]);
  if(selected.Length!=NumericMatricesOperationContract.Operations.Count)throw new InvalidDataException("AL exact contract is incomplete or a pinned signature changed.");
  const string stem="OcctSharp.Foundation.NumericMatrices.Generated";
  string sources=string.Concat(selected.Select(d=>"// Source: "+d.StableId+"\n"));
  string native=CopiedCollectionSupportEmitter.Template("numeric-matrices-native.txt");
  string declarations=string.Concat(Regex.Matches(native,@"^(?:OcctSharp_Status|void) OCCTSHARP_CALL [^\r\n{]+",RegexOptions.Multiline).Select(m=>"OCCTSHARP_API "+m.Value.Trim()+";\n"));
  string header="// <auto-generated />\n#pragma once\n#include \"../../include/OcctSharp.Native.h\"\n#include \"OcctSharp.Foundation.SharedHandles.Generated.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"+sources+declarations+"#ifdef __cplusplus\n}\n#endif\n";
  return new(version,selected.Where(d=>d.SupportState!=BindingSupportState.Manual).Select(d=>d.StableId).ToArray(),[
   new("src/OcctSharp.Native/generated/Foundation/"+stem+".h",header,OcctProductModule.Foundation,GeneratedApiLayer.Raw,"NumericMatrices"),
   new("src/OcctSharp.Native/generated/Foundation/"+stem+".cpp","// <auto-generated />\n#include \""+stem+".h\"\n"+sources+native,OcctProductModule.Foundation,GeneratedApiLayer.Raw,"NumericMatrices"),
   new("src/OcctSharp/Generated/Foundation/Foundation.NumericMatrices.Generated.cs","// <auto-generated />\n"+sources+CopiedCollectionSupportEmitter.Template("numeric-matrices-managed.txt"),OcctProductModule.Foundation,GeneratedApiLayer.SafeManaged,"NumericMatrices")]);
 }
}
