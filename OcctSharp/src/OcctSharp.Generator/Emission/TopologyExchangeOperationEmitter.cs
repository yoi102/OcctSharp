using System.Text;
using System.Text.RegularExpressions;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
namespace OcctSharp.Generator.Emission;

internal static class TopologyExchangeOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model, IReadOnlyList<string> preamble)
    {
        var selected=model.Declarations.Where(TopologyExchangeOperationContract.Contains).OrderBy(d=>d.StableId,StringComparer.Ordinal).ToArray();
        if(selected.Length==0)return new(version,[],[]);
        if(selected.Length!=TopologyExchangeOperationContract.Operations.Count)
            throw new InvalidDataException("AI exact contract is incomplete or a pinned signature changed.");
        List<GeneratedFile> files=[];
        foreach(var module in new[]{OcctProductModule.Modeling,OcctProductModule.DataExchange})
        {
            string name=module.ToString(), stem="OcctSharp."+name+".TopologyExchange.Generated";
            string native=CopiedCollectionSupportEmitter.Template("topology-exchange-"+name.ToLowerInvariant()+"-native.txt");
            var rows=selected.Where(d=>d.ProductModule==module).ToArray();
            string sources=string.Concat(rows.Select(d=>"// Source: "+d.StableId+"\n"));
            var declarations=Regex.Matches(native,@"^(?:OcctSharp_Status|void) OCCTSHARP_CALL [^\r\n{]+",RegexOptions.Multiline).Select(m=>"OCCTSHARP_API "+m.Value.Trim()+";\n");
            string header="// <auto-generated />\n#pragma once\n#include \"../../include/OcctSharp.Native.h\"\n#include \"../Foundation/OcctSharp.Foundation.SharedHandles.Generated.h\"\n#include \"../Modeling/OcctSharp.Modeling.SharedHandles.Generated.h\"\n#include \"../DataExchange/OcctSharp.DataExchange.SharedHandles.Generated.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"+sources+string.Concat(declarations)+"#ifdef __cplusplus\n}\n#endif\n";
            files.Add(new("src/OcctSharp.Native/generated/"+name+"/"+stem+".h",header,module,GeneratedApiLayer.Raw,"TopologyExchange"));
            files.Add(new("src/OcctSharp.Native/generated/"+name+"/"+stem+".cpp","// <auto-generated />\n"+string.Concat(preamble.Select(p=>"#include <"+p+">\n"))+"#include \""+stem+".h\"\n"+sources+native,module,GeneratedApiLayer.Raw,"TopologyExchange"));
            files.Add(new("src/OcctSharp/Generated/"+name+"/"+name+".TopologyExchange.Generated.cs","// <auto-generated />\n"+sources+CopiedCollectionSupportEmitter.Template("topology-exchange-"+name.ToLowerInvariant()+"-managed.txt"),module,GeneratedApiLayer.SafeManaged,"TopologyExchange"));
        }
        files.Add(new("src/OcctSharp.Native/generated/Modeling/OcctSharp.Modeling.TopologyCollectionsSupport.Generated.hxx",CopiedCollectionSupportEmitter.Template("topology-exchange-support.txt"),OcctProductModule.Modeling,GeneratedApiLayer.Raw,"TopologyExchange"));
        return new(version,selected.Where(d=>d.SupportState!=BindingSupportState.Manual).Select(d=>d.StableId).ToArray(),files);
    }
}
