using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;

namespace OcctSharp.Generator.Emission;

/// <summary>Generates bounded modeling support glue; it does not admit raw graphics handles or new declaration IDs.</summary>
public static class ModelingSupportWorkflowEmitter
{
    public const string DefeatureHistoryWorkflow = "defeature-history-v1";
    private const string ResourcePrefix = "OcctSharp.Generator.Emission.";

    public static IReadOnlyList<GeneratedFile> Emit(DiscoveryConfiguration configuration, string occtRoot)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        if (configuration.ModelingSupportWorkflows.Count == 0) return [];
        ValidateWorkflowSelection(configuration);
        ArgumentException.ThrowIfNullOrWhiteSpace(occtRoot);
        string includeRoot = Path.Combine(Path.GetFullPath(occtRoot), "inc");
        ValidateHeaderFingerprints(HeaderFingerprints(), header => File.ReadAllBytes(Path.Combine(includeRoot, header)));
        return CreateDefeatureHistoryFiles();
    }

    internal static void ValidateWorkflowSelection(DiscoveryConfiguration configuration)
    {
        if (configuration.OcctVersion != "8.0.1")
            throw new InvalidDataException("Defeature topology history support targets audited OCCT 8.0.1 headers only.");
        if (configuration.ModelingSupportWorkflows.Count != 1
            || configuration.ModelingSupportWorkflows[0] != DefeatureHistoryWorkflow)
            throw new InvalidDataException("Unknown or duplicate modeling support workflow; no output was emitted.");
    }

    internal static IReadOnlyDictionary<string, string> HeaderFingerprints()
    {
        using JsonDocument contract = JsonDocument.Parse(Template("defeature-history-contract.json"));
        return contract.RootElement.GetProperty("headers").EnumerateObject()
            .ToDictionary(row => row.Name, row => row.Value.GetString()!, StringComparer.Ordinal);
    }

    internal static void ValidateHeaderFingerprints(IReadOnlyDictionary<string, string> expected,
        Func<string, byte[]> readHeader)
    {
        foreach (var row in expected.OrderBy(row => row.Key, StringComparer.Ordinal))
        {
            if (Path.GetFileName(row.Key) != row.Key || row.Key.Contains("..", StringComparison.Ordinal))
                throw new InvalidDataException("Modeling support header contract escaped the SDK include directory.");
            if (!string.Equals(Convert.ToHexString(SHA256.HashData(readHeader(row.Key))), row.Value,
                StringComparison.Ordinal))
                throw new InvalidDataException("Audited modeling support SDK header changed: " + row.Key);
        }
    }

    internal static IReadOnlyList<GeneratedFile> CreateDefeatureHistoryFiles() =>
    [
        Generated("src/OcctSharp.Native/generated/Modeling/OcctSharp.DefeatureTopologyHistory.Generated.h", "defeature-history-header.txt", OcctProductModule.Modeling),
        Generated("src/OcctSharp.Native/generated/Modeling/OcctSharp.DefeatureTopologyHistory.Generated.cpp", "defeature-history-native.txt", OcctProductModule.Modeling),
        Generated("src/OcctSharp/Generated/Modeling/DefeatureHistory.NativeMethods.Generated.cs", "defeature-history-interop.txt", OcctProductModule.Modeling),
        Generated("src/OcctSharp/Generated/Modeling/DefeatureHistoryModeling.Generated.cs", "defeature-history-managed.txt", OcctProductModule.Modeling),
    ];

    private static GeneratedFile Generated(string path, string resource, OcctProductModule module)
    {
        string source = Template(resource).Replace("\r\n", "\n", StringComparison.Ordinal);
        if (!source.EndsWith('\n')) source += "\n";
        string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(source)));
        SupportWorkflowTemplateGuard.Require(typeof(ModelingSupportWorkflowEmitter), "defeature-history-contract.json", resource, fingerprint);
        return new(path, "// <auto-generated />\n// Modeling support workflow: " + DefeatureHistoryWorkflow
            + "; template SHA256: " + fingerprint + "\n" + source, module,
            GeneratedApiLayer.Runtime, "DefeatureHistorySupport");
    }

    private static string Template(string name)
    {
        using Stream stream = typeof(ModelingSupportWorkflowEmitter).Assembly.GetManifestResourceStream(ResourcePrefix + name)
            ?? throw new InvalidDataException("Modeling support generation input is missing: " + name);
        using StreamReader reader = new(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }
}
