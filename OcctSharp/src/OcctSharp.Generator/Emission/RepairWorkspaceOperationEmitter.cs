using System.Text.RegularExpressions;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
namespace OcctSharp.Generator.Emission;

internal static class RepairWorkspaceOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model)
    {
        var selected = model.Declarations.Where(RepairWorkspaceOperationContract.Contains)
            .OrderBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        if (selected.Length == 0) return new(version, [], []);
        if (selected.Length != RepairWorkspaceOperationContract.Operations.Count)
            throw new InvalidDataException("AJ exact contract is incomplete or a pinned signature changed.");
        const string dir = "src/OcctSharp.Native/generated/Modeling/";
        const string headerName = "OcctSharp.Modeling.RepairWorkspaces.Generated.h";
        string sources = string.Concat(selected.Select(d => "// Source: " + d.StableId + "\n"));
        List<GeneratedFile> files = [];
        List<string> exports = [];
        foreach (string part in new[] { "wiredata", "diagnostics", "sessions", "segments", "replacement" })
        {
            string native = CopiedCollectionSupportEmitter.Template("repair-workspace-" + part + "-native.txt");
            exports.AddRange(Regex.Matches(native, @"^(?:OcctSharp_Status|void) OCCTSHARP_CALL [^\r\n{]+", RegexOptions.Multiline)
                .Select(m => "OCCTSHARP_API " + m.Value.Trim() + ";\n"));
            files.Add(new(dir + "OcctSharp.Modeling.Repair" + part + ".Generated.cpp",
                "// <auto-generated />\n#include \"" + headerName + "\"\n" + sources + native,
                OcctProductModule.Modeling, GeneratedApiLayer.Raw, "RepairWorkspaces"));
        }
        string header = "// <auto-generated />\n#pragma once\n#include \"../../include/OcctSharp.Native.h\"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
            + sources + string.Concat(exports) + "#ifdef __cplusplus\n}\n#endif\n";
        files.Add(new(dir + headerName, header, OcctProductModule.Modeling, GeneratedApiLayer.Raw, "RepairWorkspaces"));
        files.Add(new(dir + "OcctSharp.Modeling.RepairSupport.Generated.hxx",
            CopiedCollectionSupportEmitter.Template("repair-workspace-support.txt"), OcctProductModule.Modeling, GeneratedApiLayer.Raw, "RepairWorkspaces"));
        foreach (string part in new[] { "data", "sessions", "diagnostics" })
            files.Add(new("src/OcctSharp/Generated/Modeling/Modeling.Repair" + part + ".Generated.cs",
                "// <auto-generated />\n" + sources + CopiedCollectionSupportEmitter.Template("repair-workspace-" + part + "-managed.txt"),
                OcctProductModule.Modeling, GeneratedApiLayer.SafeManaged, "RepairWorkspaces"));
        return new(version, selected.Where(d => d.SupportState != BindingSupportState.Manual).Select(d => d.StableId).ToArray(), files);
    }
}
