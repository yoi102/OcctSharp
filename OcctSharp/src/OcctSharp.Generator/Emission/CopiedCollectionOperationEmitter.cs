using System.Security.Cryptography;
using System.Text;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
using OcctSharp.Generator.TypeMapping;
using static OcctSharp.Generator.Emission.GeometricOperationEmitter;
using Contract = OcctSharp.Generator.Transformation.CopiedCollectionOperationContract;

namespace OcctSharp.Generator.Emission;

internal static class CopiedCollectionOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model,
        IReadOnlyList<SharedHandleScopeConfiguration> scopes, IReadOnlySet<string> existing,
        IReadOnlyList<string> preambleHeaders, bool grid = false, bool bulk = false)
    {
        var map = InitialTypeMap.FromModel(model);
        var operations = bulk ? BulkCollectionOperationContract.Operations : grid ? GridCollectionOperationContract.Operations : Contract.Operations;
        var owners = grid ? GridCollectionOperationContract.Owners : Contract.Owners;
        string family = bulk ? "bulk" : grid ? "grid" : "collection";
        var shared = scopes.ToDictionary(s => s.NativeType, StringComparer.Ordinal);
        foreach (var d in model.Declarations.Where(d => operations.ContainsKey(d.StableId)))
            if (d.NativeSignature != operations[d.StableId].Signature)
                throw new InvalidDataException("Copied collection contract signature drift: " + d.StableId);
        var selected = model.Declarations.Where(d => bulk ? BulkCollectionOperationContract.Contains(d) && !BulkCollectionOperationContract.Conversion(d) : grid ? GridCollectionOperationContract.Contains(d) : Contract.Contains(d)).OrderBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        if (selected.Length == 0) return new(version, [], []);
        List<GeneratedFile> files = bulk ? [] : [.. grid ? GridCollectionSupportEmitter.Emit() : CopiedCollectionSupportEmitter.Emit()];
        foreach (var module in selected.GroupBy(d => d.ProductModule).OrderBy(g => g.Key))
        {
            string stem = "OcctSharp." + module.Key + (bulk ? ".BulkOperations.Generated" : grid ? ".GridOperations.Generated" : ".CollectionOperations.Generated");
            var usedShared = module.SelectMany(d => d.Parameters.Select(p => p.Type.HandleTargetType)
                    .Append(d.ReturnType?.HandleTargetType).Append(Owner(d)))
                .Where(n => n is not null && shared.ContainsKey(n)).Select(n => shared[n!]).Distinct().ToArray();
            StringBuilder h = new("// <auto-generated />\n#pragma once\n#include \"../Foundation/OcctSharp.Foundation.CopiedCollections.Generated.h\"\n");
            if (grid || bulk) h.AppendLine("#include \"../Foundation/OcctSharp.Foundation.GridCollections.Generated.h\"");
            foreach (var sharedModule in usedShared.Select(s => model.Declarations.First(d => d.NativeName == s.NativeType).ProductModule).Distinct())
                h.AppendLine("#include \"../" + sharedModule + "/OcctSharp." + sharedModule + ".SharedHandles.Generated.h\"");
            h.AppendLine("#ifdef __cplusplus\nextern \"C\" {\n#endif");
            StringBuilder cpp = new(string.Concat(preambleHeaders.Select(p => "#include <" + p + ">\n"))
                + "// <auto-generated />\n#include \"" + stem + ".h\"\n#include <Standard_Failure.hxx>\nvoid OcctSharp_Internal_SetLastError(const char*);\n#include \"../Foundation/OcctSharp.Foundation.CopiedSupport.Generated.hxx\"\nusing namespace OcctSharpCollections;\n");
            if (grid || bulk) cpp.AppendLine("#include \"../Foundation/OcctSharp.Foundation.GridSupport.Generated.hxx\"");
            foreach (string owner in module.Select(Owner).Concat(usedShared.Select(s => s.NativeType)).Distinct()) cpp.AppendLine("#include <" + owner + ".hxx>");
            foreach (var s in usedShared)
            {
                cpp.AppendLine("namespace OcctSharpGenerated { const OcctSharp_" + s.ManagedTypeName + "Handle* Validate" + s.ManagedTypeName + "(const OcctSharp_" + s.ManagedTypeName + "Handle*); }");
                cpp.AppendLine("namespace OcctSharpGenerated { OcctSharp_" + s.ManagedTypeName + "Handle* Allocate" + s.ManagedTypeName + "(opencascade::handle<" + s.NativeType + ">); }");
            }
            if (bulk) { cpp.AppendLine("#include <BSplCLib.hxx>"); cpp.AppendLine(BulkCollectionGuards.Support); }
            StringBuilder cs = new("// <auto-generated />\n#nullable enable\nusing System.Runtime.InteropServices;\nusing Microsoft.Win32.SafeHandles;\nusing OcctSharp.Generated;\nusing OcctSharp.Interop;\nnamespace OcctSharp.CopiedCollections;\n");
            foreach (var group in module.GroupBy(Owner))
            {
                string owner = group.Key, name = OwnedValueOperationContract.ManagedName(owner) + "Collections";
                bool owned = owners.Contains(owner);
                string nativeOwner = NativeOwner(owner, grid);
                cs.AppendLine("/// <summary>Audited copied collection operations for " + owner + ". Synchronize native receiver mutations.</summary>\npublic " + (owned ? "sealed " : "static ") + "partial class " + name + (owned ? " : IDisposable" : "") + " {");
                if (!bulk || owner != "BSplCLib")
                    cs.AppendLine("  static " + name + "() => NativeLibraryResolver.EnsureRegistered(typeof(" + name + ").Assembly);");
                if (owned)
                {
                    string release = "occtsharp_" + family + "_" + owner.ToLowerInvariant() + "_release";
                    h.AppendLine("OCCTSHARP_API void OCCTSHARP_CALL " + release + "(void* token);");
                    cpp.AppendLine("void OCCTSHARP_CALL " + release + "(void* token) { OcctSharpOwned::Release(token, typeid(" + nativeOwner + ")); }");
                    cs.AppendLine("  private sealed class OwnerHandle : SafeHandleZeroOrMinusOneIsInvalid {\n    internal OwnerHandle(nint token) : base(true) => SetHandle(token);\n    protected override bool ReleaseHandle() { Release(handle); return true; }\n  }\n  private readonly OwnerHandle _handle;\n  private " + name + "(OwnerHandle handle) => _handle = handle;\n  private OwnerHandle NativeHandle { get { ObjectDisposedException.ThrowIf(_handle.IsClosed, this); return _handle; } }\n  private static " + name + " FromNative(nint token) { try { return new(new OwnerHandle(token)); } catch { Release(token); throw; } }\n  /// <summary>Releases the fitting algorithm after its active calls finish.</summary>\n  public void Dispose() => _handle.Dispose();\n  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + release + "\")]\n  private static partial void Release(nint token);");
                }
                HashSet<string> signatures = [];
                foreach (var d in group) EmitOperation(d, name, owned, shared, map, h, cpp, cs, signatures, grid, bulk);
                cs.AppendLine("}");
            }
            h.AppendLine("#ifdef __cplusplus\n}\n#endif");
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".h", h.ToString(), module.Key, GeneratedApiLayer.Raw, "CollectionOperations"));
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".cpp", cpp.ToString(), module.Key, GeneratedApiLayer.Raw, "CollectionOperations"));
            files.Add(new("src/OcctSharp/Generated/" + module.Key + "/" + module.Key + (bulk ? ".BulkOperations.Generated.cs" : grid ? ".GridOperations.Generated.cs" : ".CollectionOperations.Generated.cs"), cs.ToString(), module.Key, GeneratedApiLayer.SafeManaged, "CollectionOperations"));
        }
        return new(version, selected.Where(d => !operations[d.StableId].Supporting && !existing.Contains(d.StableId)).Select(d => d.StableId).ToArray(), files);
    }

    private static void EmitOperation(BindingDeclaration d, string className, bool owned,
        Dictionary<string, SharedHandleScopeConfiguration> shared, InitialTypeMap map,
        StringBuilder h, StringBuilder cpp, StringBuilder cs, HashSet<string> signatures, bool grid, bool bulk)
    {
        string owner = Owner(d), nativeOwner = NativeOwner(Owner(d), grid), family = bulk ? "bulk" : grid ? "grid" : "collection", member = d.NativeName[(owner.Length + 2)..];
        bool ctor = d.Kind == BindingDeclarationKind.Constructor;
        string export = "occtsharp_" + family + "_" + owner.ToLowerInvariant() + "_" + (ctor ? "create" : member.ToLowerInvariant()) + "_"
            + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(d.StableId)))[..12].ToLowerInvariant();
        List<string> abi = [], raw = [], friendly = [], args = [], locals = [], calls = [], outputs = [], preparations = [], publications = [], writes = [], managedCopies = [], assignments = [], cleanup = [], guards = [];
        string target = owner + "::";
        if (!ctor && !d.IsStatic)
        {
            if (owned)
            {
                abi.Add("const void* receiver"); raw.Add("OwnerHandle receiver"); args.Add("NativeHandle");
                locals.Add("auto self = OcctSharpOwned::Lease<" + (d.IsConst ? "const " : "") + nativeOwner + ">(receiver);");
            }
            else
            {
                var s = shared[owner];
                abi.Add("const OcctSharp_" + s.ManagedTypeName + "Handle* receiver"); raw.Add(s.ManagedTypeName + "Handle receiver");
                friendly.Add(s.ManagedTypeName + " receiver"); args.Add("receiver.NativeHandle"); guards.Add("ArgumentNullException.ThrowIfNull(receiver);");
                locals.Add("auto self = OcctSharpGenerated::Validate" + s.ManagedTypeName + "(receiver)->Value;");
            }
            target = "self->";
        }
        for (int i = 0; i < d.Parameters.Count; i++)
        {
            var t = d.Parameters[i].Type;
            string arg = "arg" + i, local = "local" + i;
            bool mutable = ReferenceOperationContract.IsMutableReference(t);
            if (Find(t, grid || bulk) is { } c)
            {
                abi.Add("const void* " + arg); raw.Add((IsNew(c) ? "GridHandle " : "CopiedHandle ") + arg);
                friendly.Add((mutable ? "ref " : "") + c.Friendly + " " + arg); args.Add("input" + i);
                guards.Add("using var input" + i + " = " + Interop(c) + ".Create" + c.Name + "(" + arg + ");");
                // OCCT array copy construction allocates independent storage; Sequence also copies its nodes.
                locals.Add("auto " + local + " = *OcctSharpOwned::Lease<const " + c.NativeType + ">(" + arg + ");");
                if (grid && GridCollectionOperationContract.Retained(t))
                    calls.Add("opencascade::handle<" + t.HandleTargetType + ">(new " + t.HandleTargetType + "(" + local + "))");
                else calls.Add(local);
                if (mutable)
                {
                    AddCollectionOutput("updated" + i, local, c);
                    assignments.Add(arg + " = copied_updated" + i + ";");
                }
            }
            else
            {
                var mappedType = bulk && mutable ? ReferenceOperationContract.CopiedType(t) : t;
                if (!ReferenceOperationContract.TryMap(d, mappedType, BindingTypeUsage.Parameter, map, out var p) || p?.Ownership != "ValueCopy" || mutable && !bulk)
                    throw new InvalidDataException("Unsupported copied collection parameter " + d.NativeSignature);
                abi.Add(p.AbiType + " " + arg); raw.Add(RawType(p) + " " + arg); friendly.Add((mutable ? "ref " : "") + p.ManagedFriendlyType + " " + arg); args.Add(ToRaw(arg, p));
                locals.Add("auto " + local + " = " + ToNative(arg, p, t.BaseCanonicalSpelling.Replace("const ", "", StringComparison.Ordinal)) + ";"); calls.Add(local);
                if (mutable) {
                    string name = "updated" + i;
                    abi.Add(p.AbiType + "* " + name); raw.Add("out " + RawType(p) + " " + name); args.Add("out var " + name); outputs.Add(name);
                    preparations.Add("const auto copied_" + name + " = " + FromNative(local, p) + ";"); writes.Add("*" + name + " = copied_" + name + ";");
                    assignments.Add(arg + " = " + ToFriendly(name, p) + ";");
                }
            }
        }
        string returnType = "void", returnExpression = "";
        if (!ctor && Find(d.ReturnType!, grid || bulk) is { } resultCollection)
        {
            AddCollectionOutput("result", "returned", resultCollection);
            returnType = resultCollection.Friendly; returnExpression = "copied_result";
        }
        else if (ctor || d.ReturnType!.IsOcctHandle)
        {
            string nativeResultType = ctor ? owner : d.ReturnType!.HandleTargetType!;
            returnType = ctor && owned ? className : "global::OcctSharp." + shared[nativeResultType].ManagedTypeName;
            abi.Add((ctor && owned ? "void*" : "OcctSharp_" + shared[nativeResultType].ManagedTypeName + "Handle*") + "* result");
            raw.Add("out nint result"); args.Add("out var result"); outputs.Add("result");
            if (ctor && owned)
            {
                publications.Add("Publication<" + nativeOwner + "> published_result(returned);"); writes.Add("*result = published_result.Commit();");
                returnExpression = "FromNative(result)";
            }
            else
            {
                // These calls have no other output publication; allocator cleanup is already transactional.
                writes.Add("*result = OcctSharpGenerated::Allocate" + shared[nativeResultType].ManagedTypeName + "(returned);");
                returnExpression = returnType + ".FromNative(result, \"" + export + "\")!";
            }
        }
        else
        {
            if (!map.TryMap(d.ReturnType!, BindingTypeUsage.ReturnValue, out var p) || p is null)
                throw new InvalidDataException("Unsupported copied collection return " + d.NativeSignature);
            if (p.RuleId != "TM000")
            {
                returnType = p.ManagedFriendlyType; abi.Add(p.AbiType + "* result"); raw.Add("out " + RawType(p) + " result"); args.Add("out var result"); outputs.Add("result");
                preparations.Add("const auto copied_result = " + FromNative("returned", p) + ";"); writes.Add("*result = copied_result;"); returnExpression = ToFriendly("result", p);
            }
        }
        string nativeSignature = "OcctSharp_Status OCCTSHARP_CALL " + export + "(" + (abi.Count == 0 ? "void" : string.Join(", ", abi)) + ")";
        h.AppendLine("// Source: " + d.StableId + "\nOCCTSHARP_API " + nativeSignature + ";");
        cpp.AppendLine("// Source: " + d.StableId + "\n" + nativeSignature + " {");
        foreach (var output in outputs) cpp.AppendLine("  if (!" + output + ") return OCCTSHARP_STATUS_INVALID_ARGUMENT;");
        foreach (var output in outputs) cpp.AppendLine("  *" + output + " = {};");
        if (bulk)
            for (int i = 0; i < outputs.Count; ++i)
                for (int j = i + 1; j < outputs.Count; ++j)
                    cpp.AppendLine("  if (static_cast<const void*>(" + outputs[i] + ") == static_cast<const void*>(" + outputs[j] + ")) return OCCTSHARP_STATUS_INVALID_ARGUMENT;");
        cpp.AppendLine("  return Guard([&] {");
        foreach (string local in locals) cpp.AppendLine("    " + local);
        foreach (string guard in (bulk ? BulkCollectionGuards.Emit(d) : grid ? GridCollectionGuards.Emit(d) : CopiedCollectionGuards.Emit(d))) cpp.AppendLine("    " + guard);
        string call = target + member + "(" + string.Join(", ", calls) + ")";
        if (ctor) cpp.AppendLine("    auto returned = " + (owned ? "std::make_shared<" + nativeOwner + ">(" : "opencascade::handle<" + owner + ">(new " + owner + "(") + string.Join(", ", calls) + (owned ? ");" : "));"));
        else cpp.AppendLine("    " + (returnType == "void" ? "" : "const auto& returned = ") + call + ";");
        foreach (string statement in preparations.Concat(publications).Concat(writes)) cpp.AppendLine("    " + statement);
        cpp.AppendLine("  });\n}");
        string method = ctor ? "Create" : member;
        string managedSignature = method + "(" + string.Join(", ", friendly) + ")";
        if (!signatures.Add(managedSignature)) throw new InvalidDataException("Copied collection overload collision: " + managedSignature);
        cs.AppendLine("  // Source: " + d.StableId + "\n  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + export + "\")]\n  private static partial NativeStatus Native_" + export + "(" + string.Join(", ", raw) + ");");
        cs.AppendLine("  /// <summary>Invokes " + d.NativeName + "; every collection is copied. Ref replacements publish only after all conversions succeed.</summary>\n  public " + (ctor || !owned ? "static " : "") + returnType + " " + method + "(" + string.Join(", ", friendly) + ") {");
        foreach (var guard in guards) cs.AppendLine("    " + guard);
        cs.AppendLine("    NativeError.ThrowIfFailed(Native_" + export + "(" + string.Join(", ", args) + "), \"" + export + "\");");
        if (cleanup.Count > 0) cs.AppendLine("    try {");
        foreach (var statement in managedCopies) cs.AppendLine("    " + statement);
        foreach (var assignment in assignments) cs.AppendLine("    " + assignment);
        if (returnType != "void") cs.AppendLine("    return " + returnExpression + ";");
        if (cleanup.Count > 0) { cs.AppendLine("    } finally {"); foreach (var statement in cleanup) cs.AppendLine("      " + statement); cs.AppendLine("    }"); }
        cs.AppendLine("  }");

        void AddCollectionOutput(string name, string value, Contract.Collection c)
        {
            abi.Add("void** " + name); raw.Add("out nint " + name); args.Add("out var " + name); outputs.Add(name);
            preparations.Add("auto copied_" + name + " = std::make_shared<" + c.NativeType + ">(" + value + ");");
            publications.Add("Publication<" + c.NativeType + "> published_" + name + "(copied_" + name + ");"); writes.Add("*" + name + " = published_" + name + ".Commit();");
            managedCopies.Add("var copied_" + name + " = " + Interop(c) + ".Read" + c.Name + "(" + name + ");");
            cleanup.Add(Interop(c) + ".Release(" + name + ", " + Array.IndexOf(IsNew(c) ? GridCollectionOperationContract.Collections : Contract.Collections, c) + ");");
        }
    }

    private static bool IsNew(Contract.Collection c) => Array.IndexOf(GridCollectionOperationContract.Collections, c) >= 0;
    private static string Interop(Contract.Collection c) => IsNew(c) ? "GridInterop" : "CopiedInterop";
    private static Contract.Collection? Find(BindingType t, bool grid) => grid ? GridCollectionOperationContract.Find(t) : Contract.Find(t);
    private static string NativeOwner(string owner, bool grid) => !grid ? owner : owner switch {
        "GeomAPI_Interpolate" or "Geom2dAPI_Interpolate" => "InterpolationOwner<" + owner + ">",
        "GeomAPI_PointsToBSplineSurface" => "SurfaceFitOwner", _ => owner };
    private static string Owner(BindingDeclaration d) => OwnedValueOperationContract.GetOwnerName(d);
}
