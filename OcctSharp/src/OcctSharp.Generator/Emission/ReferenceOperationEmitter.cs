using System.Text;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Model;
using OcctSharp.Generator.Transformation;
using OcctSharp.Generator.TypeMapping;
using static OcctSharp.Generator.Emission.GeometricOperationEmitter;

namespace OcctSharp.Generator.Emission;

internal static class ReferenceOperationEmitter
{
    internal static GeneratedBindingSet Emit(string version, BindingModel model,
        IReadOnlyList<SharedHandleScopeConfiguration> scopes, IReadOnlySet<string> existing,
        IReadOnlyList<string> preambleHeaders)
    {
        InitialTypeMap map = InitialTypeMap.FromModel(model);
        var owners = scopes.ToDictionary(s => s.NativeType, StringComparer.Ordinal);
        BindingTypeProjection? Map(BindingDeclaration d, BindingType t, BindingTypeUsage usage) =>
            ReferenceOperationContract.TryMap(d, t, usage, map, out var p) ? p : null;
        BindingTypeProjection? Receiver(string owner) => map.TryMap(new(owner, owner, owner, owner,
            [new(BindingTypeLayerKind.Value, false)], null, [], false, null), BindingTypeUsage.Parameter, out var p) ? p : null;
        bool Eligible(BindingDeclaration d)
        {
            if (existing.Contains(d.StableId) || !ReferenceOperationContract.Contains(d)
                || d.Access != BindingAccess.Public || d.Kind != BindingDeclarationKind.Method
                || d.SupportState is BindingSupportState.Manual or BindingSupportState.Skipped
                || d.IsDeleted || d.IsUnavailable || d.IsTemplated || d.IsVariadic || d.IsOverloadedOperator
                || (!d.IsStatic && !d.IsConst)) return false;
            string owner = GeometricOperationEligibility.Owner(d);
            if (owners.TryGetValue(owner, out var scope) && scope.ExcludedStableIds.Contains(d.StableId)) return false;
            if (!d.IsStatic && !owners.ContainsKey(owner) && Receiver(owner)?.Ownership != "ValueCopy") return false;
            if (d.ReturnType is null || Map(d, d.ReturnType, BindingTypeUsage.ReturnValue) is not { } result
                || (result.RuleId != "TM000" && result.Ownership != "ValueCopy")) return false;
            return d.Parameters.Any(p => ReferenceOperationContract.IsMutableReference(p.Type))
                && d.Parameters.All(p => Map(d, p.Type, BindingTypeUsage.Parameter) is { } projection
                    && (projection.Ownership == "ValueCopy" || (projection.RuleId == "TM006"
                        && p.Type.HandleTargetType is { } target && owners.ContainsKey(target))));
        }
        var selected = model.Declarations.Where(Eligible).OrderBy(d => d.StableId, StringComparer.Ordinal).ToArray();
        List<GeneratedFile> files = [];
        foreach (var module in selected.GroupBy(d => d.ProductModule))
        {
            string stem = "OcctSharp." + module.Key + ".ReferenceOperations.Generated";
            StringBuilder header = new("// <auto-generated />\n#pragma once\n#include \"../Geometry/OcctSharp.Geometry.Values.Generated.h\"\n");
            StringBuilder native = new("// <auto-generated />\n#include \"" + stem + ".h\"\n#include \"../Runtime/OcctSharp.Runtime.SharedSupport.Generated.hxx\"\n#include <Standard_Failure.hxx>\nvoid OcctSharp_Internal_SetLastError(const char*);\n");
            StringBuilder managed = new("// <auto-generated />\nusing System.Runtime.InteropServices;\nusing OcctSharp.Generated;\nusing OcctSharp.Interop;\nnamespace OcctSharp.ReferenceOperations;\n");
            native.Insert(0, string.Concat(preambleHeaders.Select(h => "#include <" + h + ">\n")));
            var used = module.SelectMany(d => d.Parameters.Select(p => p.Type.HandleTargetType)
                .Append(d.IsStatic ? null : GeometricOperationEligibility.Owner(d)))
                .Where(n => n is not null && owners.ContainsKey(n)).Select(n => owners[n!]).Distinct().ToArray();
            foreach (var sharedModule in used.Select(s => model.Declarations.First(d => d.NativeName == s.NativeType).ProductModule).Distinct())
                header.AppendLine("#include \"../" + sharedModule + "/OcctSharp." + sharedModule + ".SharedHandles.Generated.h\"");
            foreach (string owner in module.Select(GeometricOperationEligibility.Owner).Distinct()) native.AppendLine("#include <" + owner + ".hxx>");
            foreach (var s in used) native.AppendLine("namespace OcctSharpGenerated { const OcctSharp_" + s.ManagedTypeName + "Handle* Validate" + s.ManagedTypeName + "(const OcctSharp_" + s.ManagedTypeName + "Handle*); }");
            header.AppendLine("#ifdef __cplusplus\nextern \"C\" {\n#endif");
            foreach (var group in module.GroupBy(GeometricOperationEligibility.Owner))
            {
                string owner = group.Key;
                string className = (owner.StartsWith("gp_", StringComparison.Ordinal) ? "Gp" + owner[3..] : string.Concat(owner.Split('_'))) + "References";
                managed.AppendLine("/// <summary>Audited copied reference operations for " + owner + "; initialize ref arguments with valid values.</summary>");
                managed.AppendLine("public static partial class " + className + " {\n  static " + className + "() => NativeLibraryResolver.EnsureRegistered(typeof(" + className + ").Assembly);");
                HashSet<string> signatures = [];
                int ordinal = 0;
                foreach (var d in group)
                {
                    string member = d.NativeName[(owner.Length + 2)..];
                    string export = "occtsharp_ref_" + owner.ToLowerInvariant() + "_" + member.ToLowerInvariant() + "_" + ordinal++;
                    var result = Map(d, d.ReturnType!, BindingTypeUsage.ReturnValue)!;
                    List<string> abi = [], raw = [], friendly = [], args = [], locals = [], call = [], copies = [], writes = [], assignments = [], outputs = [];
                    string target = owner + "::";
                    if (!d.IsStatic)
                    {
                        if (owners.TryGetValue(owner, out var s))
                        {
                            abi.Add("const OcctSharp_" + s.ManagedTypeName + "Handle* receiver");
                            raw.Add(s.ManagedTypeName + "Handle receiver"); friendly.Add(s.ManagedTypeName + " receiver"); args.Add("receiver.NativeHandle");
                            target = "static_cast<const " + owner + "*>(OcctSharpGenerated::Validate" + s.ManagedTypeName + "(receiver)->Value.get())->";
                        }
                        else
                        {
                            var p = Receiver(owner)!;
                            abi.Add(p.AbiType + " receiver"); raw.Add(RawType(p) + " receiver"); friendly.Add(p.ManagedFriendlyType + " receiver"); args.Add(ToRaw("receiver", p));
                            locals.Add("const auto value = " + ToNative("receiver", p, owner) + ";"); target = "value.";
                        }
                    }
                    for (int i = 0; i < d.Parameters.Count; i++)
                    {
                        var t = d.Parameters[i].Type; var p = Map(d, t, BindingTypeUsage.Parameter)!;
                        string name = "arg" + i;
                        bool reference = ReferenceOperationContract.IsMutableReference(t);
                        if (p.RuleId == "TM006")
                        {
                            var s = owners[t.HandleTargetType!];
                            abi.Add("const OcctSharp_" + s.ManagedTypeName + "Handle* " + name);
                            raw.Add(s.ManagedTypeName + "Handle " + name); friendly.Add(s.ManagedTypeName + " " + name);
                            args.Add(name + ".NativeHandle");
                            locals.Add("auto local" + i + " = " + "OcctSharpGenerated::Validate" + s.ManagedTypeName + "(" + name + ")->Value;");
                        }
                        else
                        {
                            abi.Add(p.AbiType + " " + name); raw.Add(RawType(p) + " " + name);
                            friendly.Add((reference ? "ref " : "") + p.ManagedFriendlyType + " " + name); args.Add(ToRaw(name, p));
                            locals.Add("auto local" + i + " = " + ToNative(name, p, t.BaseCanonicalSpelling) + ";");
                        }
                        call.Add("local" + i);
                        if (reference)
                        {
                            string output = "updatedArg" + i;
                            abi.Add(p.AbiType + "* " + output); raw.Add("out " + RawType(p) + " " + output); args.Add("out " + RawType(p) + " " + output);
                            outputs.Add(output); copies.Add("const auto copied" + i + " = " + FromNative("local" + i, p) + ";");
                            writes.Add("*" + output + " = copied" + i + ";"); assignments.Add(name + " = " + ToFriendly(output, p) + ";");
                        }
                    }
                    if (result.RuleId != "TM000")
                    {
                        abi.Add(result.AbiType + "* result"); raw.Add("out " + RawType(result) + " result"); args.Add("out " + RawType(result) + " result"); outputs.Add("result");
                        copies.Add("const auto copiedResult = " + FromNative("returned", result) + ";"); writes.Add("*result = copiedResult;");
                    }
                    string signature = "OcctSharp_Status OCCTSHARP_CALL " + export + "(" + string.Join(", ", abi) + ")";
                    header.AppendLine("// Source: " + d.StableId + "\nOCCTSHARP_API " + signature + ";");
                    native.AppendLine("// Source: " + d.StableId + "\n" + signature + " {");
                    foreach (string output in outputs) native.AppendLine("  if (" + output + " == nullptr) { OcctSharp_Internal_SetLastError(\"Null reference operation output.\"); return OCCTSHARP_STATUS_INVALID_ARGUMENT; }");
                    foreach (string output in outputs) native.AppendLine("  *" + output + " = {};");
                    native.AppendLine("  OcctSharp_Internal_SetLastError(\"\");\n  try {");
                    foreach (string local in locals) native.AppendLine("    " + local);
                    native.AppendLine("    " + (result.RuleId == "TM000" ? "" : "const auto returned = ") + target + member + "(" + string.Join(", ", call) + ");");
                    foreach (string copy in copies) native.AppendLine("    " + copy);
                    foreach (string write in writes) native.AppendLine("    " + write);
                    native.AppendLine("    return OCCTSHARP_STATUS_SUCCESS;\n  }\n  catch (const OcctSharpGenerated::GeneratedOperationFailure& error) { OcctSharp_Internal_SetLastError(error.what()); return error.Status; }\n  catch (const Standard_Failure& error) { OcctSharp_Internal_SetLastError(error.GetMessageString()); return OCCTSHARP_STATUS_OCCT_FAILURE; }\n  catch (const std::exception& error) { OcctSharp_Internal_SetLastError(error.what()); return OCCTSHARP_STATUS_STANDARD_EXCEPTION; }\n  catch (...) { OcctSharp_Internal_SetLastError(\"Unknown reference operation exception.\"); return OCCTSHARP_STATUS_UNKNOWN_EXCEPTION; }\n}");
                    string methodName = member; int suffix = 2;
                    while (!signatures.Add(methodName + "(" + string.Join(",", friendly) + ")")) methodName = member + suffix++;
                    managed.AppendLine("  // Source: " + d.StableId + "\n  [LibraryImport(\"OcctSharp.Native\", EntryPoint = \"" + export + "\")]\n  private static partial NativeStatus Native_" + export + "(" + string.Join(", ", raw) + ");");
                    managed.AppendLine("  /// <summary>Invokes " + d.NativeName + ". Initialize ref values with valid inputs; assignments occur only on success, in parameter order.</summary>\n  public static " + result.ManagedFriendlyType + " " + EnumBindingEmitter.ToIdentifier(methodName) + "(" + string.Join(", ", friendly) + ") {\n    NativeError.ThrowIfFailed(Native_" + export + "(" + string.Join(", ", args) + "), \"" + export + "\");");
                    foreach (string assignment in assignments) managed.AppendLine("    " + assignment);
                    if (result.RuleId != "TM000") managed.AppendLine("    return " + ToFriendly("result", result) + ";");
                    managed.AppendLine("  }");
                }
                managed.AppendLine("}");
            }
            header.AppendLine("#ifdef __cplusplus\n}\n#endif");
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".h", header.ToString(), module.Key, GeneratedApiLayer.Raw, "ReferenceOperations"));
            files.Add(new("src/OcctSharp.Native/generated/" + module.Key + "/" + stem + ".cpp", native.ToString(), module.Key, GeneratedApiLayer.Raw, "ReferenceOperations"));
            files.Add(new("src/OcctSharp/Generated/" + module.Key + "/" + module.Key + ".ReferenceOperations.Generated.cs", managed.ToString(), module.Key, GeneratedApiLayer.SafeManaged, "ReferenceOperations"));
        }
        return new(version, selected.Select(d => d.StableId).ToArray(), files);
    }
}
