using OcctSharp.Generator.Model;

namespace OcctSharp.Generator.Emission;

/// <summary>One registry for every owned projection in the native DLL.</summary>
internal static class OwnedValueSupportEmitter
{
    internal static IEnumerable<GeneratedFile> Emit()
    {
        yield return new("src/OcctSharp.Native/generated/Runtime/OcctSharp.Runtime.OwnedSupport.Generated.hxx", Header,
            OcctProductModule.Runtime, GeneratedApiLayer.Raw, "OwnedValues.Support");
        yield return new("src/OcctSharp.Native/generated/Runtime/OcctSharp.Runtime.OwnedSupport.Generated.cpp", Source,
            OcctProductModule.Runtime, GeneratedApiLayer.Raw, "OwnedValues.Support");
    }

    private const string Header = """
        // <auto-generated />
        #pragma once
        #include "OcctSharp.Runtime.SharedSupport.Generated.hxx"
        #include <memory>
        #include <typeindex>
        namespace OcctSharpOwned {
        void* Register(std::shared_ptr<void> value, std::type_index type);
        std::shared_ptr<void> Acquire(const void* token, std::type_index type);
        void Release(const void* token, std::type_index type) noexcept;
        template<class T> std::shared_ptr<T> Lease(const void* token) {
          return std::static_pointer_cast<T>(Acquire(token, typeid(T)));
        }
        template<class H, class T> H* Publish(std::shared_ptr<T> value) {
          return static_cast<H*>(Register(std::move(value), typeid(T)));
        }
        }

        """;

    private const string Source = """
        // <auto-generated />
        #include "OcctSharp.Runtime.OwnedSupport.Generated.hxx"
        #include <cstdint>
        #include <limits>
        #include <mutex>
        #include <unordered_map>
        namespace OcctSharpOwned {
        namespace {
        struct Entry { std::shared_ptr<void> Value; std::type_index Type; };
        std::mutex RegistryMutex;
        std::unordered_map<uintptr_t, Entry> Registry;
        uintptr_t NextToken = 1;
        }
        void* Register(std::shared_ptr<void> value, std::type_index type) {
          if (!value) throw std::invalid_argument("Cannot register an empty owned value.");
          std::lock_guard<std::mutex> lock(RegistryMutex);
          // Tokens never wrap or repeat, including when insertion fails.
          if (NextToken == std::numeric_limits<uintptr_t>::max())
            throw std::overflow_error("Owned value token space exhausted.");
          const uintptr_t token = NextToken++;
          Registry.emplace(token, Entry{std::move(value), type});
          return reinterpret_cast<void*>(token);
        }
        std::shared_ptr<void> Acquire(const void* token, std::type_index type) {
          if (!token) throw OcctSharpGenerated::GeneratedOperationFailure(
            OCCTSHARP_STATUS_INVALID_ARGUMENT, "Null owned value handle.");
          std::lock_guard<std::mutex> lock(RegistryMutex);
          const auto found = Registry.find(reinterpret_cast<uintptr_t>(token));
          if (found == Registry.end() || found->second.Type != type)
            throw OcctSharpGenerated::GeneratedOperationFailure(
              OCCTSHARP_STATUS_INVALID_ARGUMENT, "Stale or wrong-type owned value handle.");
          return found->second.Value;
        }
        void Release(const void* token, std::type_index type) noexcept {
          try {
            std::shared_ptr<void> retired;
            {
              std::lock_guard<std::mutex> lock(RegistryMutex);
              const auto found = Registry.find(reinterpret_cast<uintptr_t>(token));
              if (found == Registry.end() || found->second.Type != type) return;
              retired = std::move(found->second.Value);
              Registry.erase(found);
            }
            // Run destructors outside the registry lock; existing calls keep their leases.
          } catch (...) { }
        }
        }

        """;
}
