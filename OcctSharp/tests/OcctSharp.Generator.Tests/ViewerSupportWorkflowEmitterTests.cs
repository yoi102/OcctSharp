using System.Security.Cryptography;
using System.Text;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Emission;

namespace OcctSharp.Generator.Tests;

public sealed class ViewerSupportWorkflowEmitterTests
{
    private static readonly string[] ExpectedHeaders = ["A.hxx", "B.hxx"];
    private static DiscoveryConfiguration Configuration(params string[] workflows) => new("1.13", "8.0.1",
        "test", [], new Dictionary<string, string>()) { ViewerSupportWorkflows = workflows };

    [Fact]
    public void DisabledWorkflowDoesNotReadSdkOrProduceOutput()
        => Assert.Empty(ViewerSupportWorkflowEmitter.Emit(Configuration(), "missing-sdk"));

    [Theory]
    [InlineData("unknown")]
    [InlineData("RENDER-HEALTH-V1")]
    [InlineData("../render-health-v1")]
    public void UnknownWorkflowRefusesBeforeMissingSdkAccess(string workflow)
        => Assert.Throws<InvalidDataException>(() => ViewerSupportWorkflowEmitter.Emit(Configuration(workflow), "missing-sdk"));

    [Fact]
    public void DuplicateWorkflowRefusesBeforeAnySdkAccess()
        => Assert.Throws<InvalidDataException>(() => ViewerSupportWorkflowEmitter.Emit(
            Configuration("render-health-v1", "render-health-v1"), "missing-sdk"));

    [Fact]
    public void OtherSdkVersionDoesNotReuseAnAuditedContract()
        => Assert.Throws<InvalidDataException>(() => ViewerSupportWorkflowEmitter.Emit(
            Configuration("render-health-v1") with { OcctVersion = "8.0.2" }, "missing-sdk"));

    [Fact]
    public void MissingSdkHeadersRefuseBeforeEmission()
        => Assert.Throws<DirectoryNotFoundException>(() => ViewerSupportWorkflowEmitter.Emit(
            Configuration("render-health-v1"), Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"))));

    [Fact]
    public void HeaderIdentityUsesBytesAndVisitsEveryHeaderInStableOrder()
    {
        byte[] bytes = Encoding.UTF8.GetBytes("audited-header\n");
        string hash = Convert.ToHexString(SHA256.HashData(bytes));
        var headers = new Dictionary<string, string> { ["B.hxx"] = hash, ["A.hxx"] = hash };
        List<string> read = [];
        ViewerSupportWorkflowEmitter.ValidateHeaderFingerprints(headers, name => { read.Add(name); return bytes; });
        Assert.Equal(ExpectedHeaders, read);
        Assert.Throws<InvalidDataException>(() => ViewerSupportWorkflowEmitter.ValidateHeaderFingerprints(headers,
            _ => Encoding.UTF8.GetBytes("audited-header\r\n")));
    }

    [Theory]
    [InlineData("../A.hxx")]
    [InlineData("sub/A.hxx")]
    public void EscapedHeaderRefusesWithoutReading(string name)
    {
        bool read = false;
        Assert.Throws<InvalidDataException>(() => ViewerSupportWorkflowEmitter.ValidateHeaderFingerprints(
            new Dictionary<string, string> { [name] = "unused" }, _ => { read = true; return []; }));
        Assert.False(read);
    }

    [Fact]
    public void TemplatesEmitDeterministicManifestOwnedFilesWithoutGraphicsHandles()
    {
        var first = ViewerSupportWorkflowEmitter.CreateRenderingHealthFiles();
        Assert.Equal(first.ToArray(), ViewerSupportWorkflowEmitter.CreateRenderingHealthFiles().ToArray());
        Assert.Equal(4, first.Count);
        Assert.Equal(4, first.Select(file => file.RelativePath).Distinct().Count());
        Assert.Equal(4, ViewerSupportWorkflowEmitter.HeaderFingerprints().Count);
        foreach (var file in first)
        {
            Assert.StartsWith("// <auto-generated />\n", file.Content, StringComparison.Ordinal);
            Assert.EndsWith("\n", file.Content, StringComparison.Ordinal);
            Assert.DoesNotContain("\r", file.Content, StringComparison.Ordinal);
        }
        string native = first.Single(file => file.RelativePath.EndsWith(".cpp", StringComparison.Ordinal)).Content;
        Assert.True(native.IndexOf("*output = 0;", StringComparison.Ordinal) < native.IndexOf("ValidateViewerThread", StringComparison.Ordinal));
        Assert.Contains("return Guard([&]", native, StringComparison.Ordinal);
        string interop = first.Single(file => file.RelativePath.EndsWith("NativeMethods.Generated.cs", StringComparison.Ordinal)).Content;
        Assert.Contains("out int flags", interop, StringComparison.Ordinal);
        Assert.DoesNotContain("OpenGl_Context", interop, StringComparison.Ordinal);
        Assert.DoesNotContain("IntPtr", interop, StringComparison.Ordinal);
    }
}
