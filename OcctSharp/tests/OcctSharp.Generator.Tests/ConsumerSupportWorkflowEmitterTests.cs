using System.Text.Json;
using System.Text.Json.Nodes;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Emission;

namespace OcctSharp.Generator.Tests;

public sealed class ConsumerSupportWorkflowEmitterTests
{
    private static DiscoveryConfiguration Configuration(params string[] workflows) => new("1.13", "8.0.1",
        "test", [], new Dictionary<string, string>()) { ConsumerSupportWorkflows = workflows };
    [Fact]
    public void DisabledDoesNotAccessSdk() => Assert.Empty(ConsumerSupportWorkflowEmitter.Emit(Configuration(), "missing"));
    [Theory]
    [InlineData("unknown")]
    [InlineData("EXACT-CONSUMER-V1")]
    public void UnknownWorkflowRefusesBeforeSdk(string workflow) => Assert.Throws<InvalidDataException>(
        () => ConsumerSupportWorkflowEmitter.Emit(Configuration(workflow), "missing"));
    [Fact]
    public void DuplicateWorkflowRefuses() => Assert.Throws<InvalidDataException>(() =>
        ConsumerSupportWorkflowEmitter.Emit(Configuration("exact-consumer-v1", "exact-consumer-v1"), "missing"));
    [Fact]
    public void DifferentSdkRefuses() => Assert.Throws<InvalidDataException>(() =>
        ConsumerSupportWorkflowEmitter.Emit(Configuration("exact-consumer-v1") with { OcctVersion = "8.0.2" }, "missing"));
    [Fact]
    public void DeterministicTemplatesHaveNoDeclarationCredit()
    {
        using var contract = ConsumerSupportWorkflowEmitter.ReadContract();
        var files = ConsumerSupportWorkflowEmitter.CreateFiles(contract.RootElement);
        Assert.Equal(files.ToArray(), ConsumerSupportWorkflowEmitter.CreateFiles(contract.RootElement).ToArray());
        Assert.Equal(41, files.Count);
        Assert.Empty(contract.RootElement.GetProperty("newAdmittedDeclarationStableIds").EnumerateArray());
        foreach (var file in files)
        {
            Assert.StartsWith("// <auto-generated />\n", file.Content, StringComparison.Ordinal);
            Assert.DoesNotContain("\r", file.Content, StringComparison.Ordinal);
        }
        Assert.Equal(3, files.Single(f => f.RelativePath.Contains("BrepReferenceSnapshot", StringComparison.Ordinal)).Content
            .Split("ConsumerSerializationRuntime.Require();", StringSplitOptions.None).Length - 1);
        Assert.Equal(3, files.Single(f => f.RelativePath.Contains("BrepOccurrenceSnapshot", StringComparison.Ordinal)).Content
            .Split("ConsumerSerializationRuntime.Require();", StringSplitOptions.None).Length - 1);
    }
    [Theory]
    [InlineData("output", "src/OcctSharp.Native/src/Manual.cpp")]
    [InlineData("output", "src/OcctSharp/Generated/Modeling/../escaped.cs")]
    [InlineData("template", "../consumer-serialization-header.txt")]
    [InlineData("templateSha256", "changed")]
    [InlineData("module", "Draw")]
    public void ContractTamperingRefuses(string key, string value)
    {
        using var original = ConsumerSupportWorkflowEmitter.ReadContract();
        var node = JsonNode.Parse(original.RootElement.GetRawText())!;
        node["files"]![0]![key] = value;
        using var mutated = JsonDocument.Parse(node.ToJsonString());
        Assert.Throws<InvalidDataException>(() => ConsumerSupportWorkflowEmitter.CreateFiles(mutated.RootElement));
    }
    [Fact]
    public void DuplicateOutputRefuses()
    {
        using var original = ConsumerSupportWorkflowEmitter.ReadContract();
        var node = JsonNode.Parse(original.RootElement.GetRawText())!;
        node["files"]!.AsArray().Add(node["files"]![0]!.DeepClone());
        using var mutated = JsonDocument.Parse(node.ToJsonString());
        Assert.Throws<InvalidDataException>(() => ConsumerSupportWorkflowEmitter.CreateFiles(mutated.RootElement));
    }
}
