using System.Security.Cryptography;
using System.Text;
using OcctSharp.Generator.Discovery;
using OcctSharp.Generator.Emission;

namespace OcctSharp.Generator.Tests;

public sealed class ModelingSupportWorkflowEmitterTests
{
    private static readonly string[] ExpectedHeaderOrder = ["A.hxx", "B.hxx"];

    private static DiscoveryConfiguration Configuration(params string[] workflows) => new("1.13", "8.0.1",
        "test", [], new Dictionary<string, string>()) { ModelingSupportWorkflows = workflows };

    [Fact]
    public void DisabledWorkflowDoesNotReadSdkOrProduceOutput()
        => Assert.Empty(ModelingSupportWorkflowEmitter.Emit(Configuration(), "missing-sdk"));

    [Theory]
    [InlineData("unknown")]
    [InlineData("DEFEATURE-HISTORY-V1")]
    [InlineData("../defeature-history-v1")]
    public void UnknownWorkflowRefusesBeforeMissingSdkAccess(string workflow)
        => Assert.Throws<InvalidDataException>(() => ModelingSupportWorkflowEmitter.Emit(Configuration(workflow), "missing-sdk"));

    [Fact]
    public void DuplicateWorkflowRefusesBeforeAnySdkAccess()
        => Assert.Throws<InvalidDataException>(() => ModelingSupportWorkflowEmitter.Emit(
            Configuration("defeature-history-v1", "defeature-history-v1"), "missing-sdk"));

    [Fact]
    public void OtherSdkVersionDoesNotReuseAnAuditedContract()
        => Assert.Throws<InvalidDataException>(() => ModelingSupportWorkflowEmitter.Emit(
            Configuration("defeature-history-v1") with { OcctVersion = "8.0.2" }, "missing-sdk"));

    [Fact]
    public void MissingSdkHeadersRefuseBeforeEmission()
        => Assert.Throws<DirectoryNotFoundException>(() => ModelingSupportWorkflowEmitter.Emit(
            Configuration("defeature-history-v1"), Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"))));

    [Fact]
    public void HeaderIdentityUsesBytesAndVisitsEveryHeaderInStableOrder()
    {
        byte[] bytes = Encoding.UTF8.GetBytes("audited-header\n");
        string hash = Convert.ToHexString(SHA256.HashData(bytes));
        var headers = new Dictionary<string, string> { ["B.hxx"] = hash, ["A.hxx"] = hash };
        List<string> read = [];
        ModelingSupportWorkflowEmitter.ValidateHeaderFingerprints(headers, name => { read.Add(name); return bytes; });
        Assert.Equal(ExpectedHeaderOrder, read);
        Assert.Throws<InvalidDataException>(() => ModelingSupportWorkflowEmitter.ValidateHeaderFingerprints(headers,
            _ => Encoding.UTF8.GetBytes("audited-header\r\n")));
    }

    [Theory]
    [InlineData("../A.hxx")]
    [InlineData("sub/A.hxx")]
    public void EscapedHeaderRefusesWithoutReading(string name)
    {
        bool read = false;
        Assert.Throws<InvalidDataException>(() => ModelingSupportWorkflowEmitter.ValidateHeaderFingerprints(
            new Dictionary<string, string> { [name] = "unused" }, _ => { read = true; return []; }));
        Assert.False(read);
    }

    [Fact]
    public void TemplatesEmitDeterministicManifestOwnedFilesWithoutRawHistoryHandles()
    {
        var first = ModelingSupportWorkflowEmitter.CreateDefeatureHistoryFiles();
        Assert.Equal(first.ToArray(), ModelingSupportWorkflowEmitter.CreateDefeatureHistoryFiles().ToArray());
        Assert.Equal(4, first.Count);
        Assert.Equal(4, first.Select(file => file.RelativePath).Distinct().Count());
        Assert.Equal(4, ModelingSupportWorkflowEmitter.HeaderFingerprints().Count);
        foreach (var file in first)
        {
            Assert.StartsWith("// <auto-generated />\n", file.Content, StringComparison.Ordinal);
            Assert.EndsWith("\n", file.Content, StringComparison.Ordinal);
            Assert.DoesNotContain("\r", file.Content, StringComparison.Ordinal);
        }
        string native = first.Single(file => file.RelativePath.EndsWith(".cpp", StringComparison.Ordinal)).Content;
        Assert.Contains("history->Merge(unify.History())", native, StringComparison.Ordinal);
        Assert.Contains("InputGraph graph(inputs, 1)", native, StringComparison.Ordinal);
        Assert.Contains("StableDefeatureDiagnosticMap", native, StringComparison.Ordinal);
        Assert.Contains("builder.IsDeleted", native, StringComparison.Ordinal);
        Assert.True(native.IndexOf("*output = nullptr", StringComparison.Ordinal) < native.IndexOf("InputGraph graph", StringComparison.Ordinal));
        string managed = first.Single(file => file.RelativePath.Contains("DefeatureHistoryModeling", StringComparison.Ordinal)).Content;
        Assert.Contains("IReadOnlyList<RepairSelection>", managed, StringComparison.Ordinal);
        Assert.Contains("LocalFeatureBridge.Select", managed, StringComparison.Ordinal);
        Assert.Contains("AuthoringBridge.WithInputs", managed, StringComparison.Ordinal);
        Assert.DoesNotContain("BRepTools_History", managed, StringComparison.Ordinal);
    }
    [Fact]
    public void StandardManifestWriterAcceptsEveryWorkflowPathAndRetainsItsExactBytes()
    {
        string temporaryRoot = Path.GetFullPath(Path.GetTempPath());
        string output = Path.GetFullPath(Path.Combine(temporaryRoot, "occtsharp-e5-writer-" + Guid.NewGuid().ToString("N")));
        Assert.StartsWith(temporaryRoot.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, output, StringComparison.OrdinalIgnoreCase);
        try
        {
            var files = ModelingSupportWorkflowEmitter.CreateDefeatureHistoryFiles();
            var manifest = GeneratedOutputWriter.Replace(output, new("8.0.1", [], files));
            Assert.Equal(4, manifest.Files.Count);
            Assert.Empty(manifest.SourceStableIds);
            foreach (var file in files)
                Assert.Equal(Encoding.UTF8.GetBytes(file.Content), File.ReadAllBytes(Path.Combine(output, file.RelativePath)));
        }
        finally
        {
            if (Directory.Exists(output)) Directory.Delete(output, true);
        }
    }

}
